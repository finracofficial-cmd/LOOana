# 商品別: 個数とLPVあたり個数、構成と商品内の分解
def units(d,k): g=G[d].get(k,0); assert g%pr[k]==0,(d,k); return g//pr[k]
def mixwithin(a,b):
    ks=[k for k in set(M[a])|set(M[b]) if k!='カタログ']
    La=sum(M[a].get(k,[0]*4)[3] for k in ks); Lb=sum(M[b].get(k,[0]*4)[3] for k in ks)
    Ua=sum(units(a,k) for k in ks if k in pr); Ub=sum(units(b,k) for k in ks if k in pr)
    print(f"\n--- {a} vs {b}（カタログ除く・Shopify個数 ÷ Meta LPV）--- 全体 {Ua}/{La}={Ua/La*100:.2f}個/100来訪 vs {Ub}/{Lb}={Ub/Lb*100:.2f}")
    mix=within=0
    rows=[]
    for k in ks:
        la=M[a].get(k,[0]*4)[3]; lb=M[b].get(k,[0]*4)[3]; ua=units(a,k); ub=units(b,k)
        ra=ua/la if la else 0; rb=ub/lb if lb else 0
        rows.append((k,ua,la,ub,lb,ra,rb))
        if la and lb: mix+=(la/La-lb/Lb)*rb; within+=la/La*(ra-rb)
        elif la: mix+=la/La*ra   # 片方にしかない商品は構成側に入れる
        elif lb: mix+=-(lb/Lb)*rb
    for k,ua,la,ub,lb,ra,rb in sorted(rows,key=lambda r:-(r[1]-r[3])):
        print(f" {k}: {ua}個/{la}来訪（{ra*100:.1f}） vs {ub}個/{lb}来訪（{rb*100:.1f}）  個数差{ua-ub:+d}")
    print(f" 分解(個/100来訪): 構成 {mix*100:+.2f} ・ 商品内 {within*100:+.2f} ・ 計 {(Ua/La-Ub/Lb)*100:+.2f}")
