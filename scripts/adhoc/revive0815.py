print(f"    原価率 {dcost/D['gross']:.1%}  MER {dnet/D['ad']:.2f}（分岐 {1/(1-dcost/D['gross']):.2f}）")
print(f"    CPA(注文) {dcpa:,.0f}円  粗利/注文 {dgp_ord:,.0f}円  → **倍率 {dgp_ord/dcpa:.2f}**（1.3以下は全負けゾーン）")
print(f"    帳簿上の利益 {dprof:+,}円（A案＝返品を控除しない）")
print(f"    ⚠️ 返品 {D['ret']:,}円（返品率 {D['ret']/D['gross']:.1%}・基準3%の4.2倍）")
print(f"    返金は現金で出ていき、CJ品は返送しないので原価も戻らない")
print(f"    → **実質の現金損益 {dprof - D['ret']:+,}円。停止前は赤字だった。**")

