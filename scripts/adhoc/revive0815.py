print('■ ① 5WAY腰掛けファン ── 季節減衰を織り込むと結論が変わる')
# 週次MER（Shopify実売÷Meta広告費・実測）
WK = [('7/18-24', 4.82), ('7/25-31', 4.13), ('8/01-07', 2.60), ('8/08-14', 1.99)]
BR5, GM5 = 1.59, 1 - 1848 / 4980            # 分岐MER / 粗利率
print(f"  週次MER: " + " → ".join(f"{k} {v:.2f}" for k, v in WK))
dec = WK[-1][1] / WK[-2][1] - 1
print(f"  直近2週の変化: {WK[-2][1]/WK[-3][1]-1:+.0%} → {dec:+.0%}  ＝ 2週連続−15%以上 かつ 残4週 → 先回り縮小の条件を満たす")
print(f"\n  {'限界MERの取り方':<34}{'限界MER':>9}{'削減1円あたり利益':>18}")
for lbl, m in [('平均1.99 × 0.6', 1.99*0.6), ('平均1.99 × 0.7', 1.99*0.7), ('平均1.99 × 0.8', 1.99*0.8)]:
    print(f"  {lbl:<34}{m:>9.2f}{1-m*GM5:>+18.3f}")
print(f"  ── ここまでは7日窓の平均MERベース。季節商品はこれが古い（週{dec:+.0%}で陳腐化） ──")
for lbl, m in [('平均×0.6 × 週次減衰', 1.99*0.6*(1+dec)), ('平均×0.7 × 週次減衰', 1.99*0.7*(1+dec)),
               ('平均×0.8 × 週次減衰', 1.99*0.8*(1+dec))]:
    print(f"  {lbl:<34}{m:>9.2f}{1-m*GM5:>+18.3f}")
cut = 10500 - 7800
print(f"\n  → 減衰を織り込むと3端すべてで正。10,500 → 7,800（−25%）で 週 +{cut*7*(1-1.99*0.7*(1+dec)*GM5):,.0f}円")

print('\n■ ② 日傘2種 ── 削るべきなのは「長い方」ではなく「短い方」')
UMB = {  # 窓: (完全遮光の実売,広告費, 形状記憶の実売,広告費)
 '3日': (71463, 44564, 126492, 98412), '5日': (149649, 83295, 249996, 169870),
 '7日': (203433, 142253, 397404, 242673)}
BRU, GMU = 1.36, 1 - 1309 / 4980
print(f"  {'窓':<5}{'完全遮光MER':>12}{'余裕':>7}{'形状記憶MER':>12}{'余裕':>7}   削減1円あたり(完全遮光 / 形状記憶・×0.7)")
for k, (nz, cz, nk, ck) in UMB.items():
    mz, mk = nz/cz, nk/ck
    print(f"  {k:<5}{mz:>12.2f}{mz-BRU:>+7.2f}{mk:>12.2f}{mk-BRU:>+7.2f}   "
          f"{1-mz*0.7*GMU:>+8.3f} / {1-mk*0.7*GMU:>+8.3f}")
print("  → 完全遮光は3窓すべて分岐超え・削減の符号が端で割れる → 触らない")
print("  → 形状記憶は3窓すべて余裕<0.30・削減の符号が3窓×3端すべて正 → −25%が正当（ただし8/18の統合判定と同時に）")

print('\n■ ③ 復活候補2品 ── 停止前の実績を「倍率」で評価する')
# 壁掛けディスペンサー 2026-06-29〜08-02（広告稼働の全期間・Shopify実測）
D = dict(gross=895320, disc=38581, orders=105, ret=112913,
         q3=94, q2=40, c3=2528, c2=1981, p3=6980, p2=5980, ad=475492)
dq = D['q3'] + D['q2']; dcost = D['q3']*D['c3'] + D['q2']*D['c2']
