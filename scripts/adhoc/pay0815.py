# -*- coding: utf-8 -*-
"""決済手段を足すと手数料が上がる。それを取り返すのに必要なレジ完了率の改善幅を出す。

土台は 8/08-14 の実測（cvr0815.py と同じ）。
新しい決済手段の手数料率は契約時に確定するので、ここでは「上がり幅」を振って感度を見る。
"""
import runpy
g = runpy.run_path('scripts/daily/d0815.py')
NET7 = sum(g['N7'].values()); COST7 = sum(g['K7'].values())
CR = COST7 / NET7; FEE = 0.03452; KEEP = 1 - CR - FEE
SESS, CK, CP = 37720, 2099, 1028           # 8/08-14 Shopify実測（セッション）
AOV = NET7 / CP

print(f'■ 前提（8/08-14 実測）')
print(f'  実売 {NET7:,.0f}円 / 原価率 {CR:.1%} / 現行の決済手数料ブレンド {FEE:.3%}')
print(f'  レジ到達 {CK:,} → 購入完了 {CP:,}（完了率 {CP/CK:.1%}）/ セッション単価 {AOV:,.0f}円')
print(f'  増えた売上に広告費は乗らないので、手取りは売上 × {KEEP:.3f}\n')

print('■ 「手数料が上がる分」を取り返すのに必要なレジ完了率の改善')
print('  読み方: 新決済が売上の s% を取り、その分の手数料が現行より d ポイント高いとき、')
print('          必要な追加注文は  s × d ÷ {:.3f}  で決まる。\n'.format(KEEP))
print(f"  {'新決済の売上シェア':>18}{'手数料の上乗せ':>14}{'必要な追加注文':>14}{'必要なレジ完了率':>16}")
for s in (0.10, 0.20, 0.30):
    for d in (0.005, 0.0125, 0.02):
        need_ratio = s * d / KEEP                      # 注文の何%増が必要か
        need_orders = CP * need_ratio
        print(f"  {s:>18.0%}{d:>14.2%}{need_orders:>+14.1f}{(CP+need_orders)/CK:>16.2%}")
print(f"\n  現在のレジ完了率 {CP/CK:.2%}。上の表の「必要なレジ完了率」はどれも 49.5% 未満。")
print(f"  つまり完了率が 0.5pt 上がれば、手数料の上乗せは全部回収できる。")
print(f"  参考: 完了率を1か月前の 51.6% に戻すと利益 +{(CK*0.5159-CP)*AOV*KEEP:,.0f}円/7日。")
print(f"       手数料の心配は、この額の前ではノイズ。")
