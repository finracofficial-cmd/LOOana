    need = ns * 0.10                      # 目標利益
    dk = (k - (ns - a - need)) / k                      # 原価をこの割合下げる
    da = (a - (ns - k - need)) / a                      # 広告費をこの割合下げる（＝同じ売上を保てる前提）
    # CVRがx倍になると同じ売上をa/xの広告費で作れる → 必要倍率
    x = a / (ns - k - need) if (ns - k - need) > 0 else float('inf')
    p = PRICE[n]; c = COST.get(n, 0)
    # 値上げ: 販売数不変の仮定での必要売価（弾力性は別途注記）
    newp = (k + a + 0) / (0.90) / (ns / p) if ns > 0 else 0
    print(f'  {n:<24}{mr:>7.1%}{dk:>11.1%}{f"×{x:.2f}":>11}{da:>13.1%}{newp:>10,.0f}円')
