# -*- coding: utf-8 -*-
"""ナノバブルシャワーヘッドの売価を 5,980 / 6,980 / 7,980 で比較する。

原価はShopify実測 2,255円。価格帯別CVRは全店実測（7日 8/02-08）。
値下げの弾力性は当店で唯一の実測（姿勢サポートチェア 7,980→5,980 で CVR 2.13%→2.48%）を使う。
"""
import math
COST = 2255
BAND = {3980: 0.0406, 4980: 0.0381, 6480: 0.0270, 8980: 0.0053}   # 5,980-6,980は同一バンド2.70%
# 当店唯一の値下げ実測から弾力性を出す
e = math.log(0.0248 / 0.0213) / math.log(5980 / 7980)
print(f'■ 当店唯一の値下げ実測（姿勢サポートチェア 7,980→5,980）')
print(f'  価格 {5980/7980-1:+.1%} → CVR 2.13% → 2.48%（{0.0248/0.0213-1:+.1%}）')
print(f'  → 弾力性 {e:+.3f}（価格1%でCVR {e:.3f}%）\n')

print('■ 価格別の経済性')
print(f"  {'売価':>7}{'原価率':>8}{'粗利/個':>9}{'分岐MER':>9}{'分岐CPA(注文)':>14}{'目標MER':>9}   価格帯")
for p in (5980, 6980, 7980):
    r = COST / p; gp = p - COST
    band = '5,980-6,980（実測CVR 2.70%）' if p in (5980, 6980) else '6,980と8,980の間（未実測）'
    print(f"  {p:>7,}{r:>8.1%}{gp:>9,}{1/(1-r):>9.3f}{gp*1.05:>14,.0f}{1/(1-r-0.35):>9.3f}   {band}")

print('\n■ 6,980円を基準に、他の価格へ動かす損益')
base = 6980; gpb = base - COST
for p in (5980, 7980):
    gp = p - COST
    need = 1 / (gp / gpb) - 1                       # 粗利総額が同じになるのに必要なCVR変化
    exp = (p / base) ** e - 1                       # 弾力性から見込まれるCVR変化
    print(f"\n  {base:,} → {p:,}（{p/base-1:+.1%}）")
    print(f"    粗利/個 {gpb:,} → {gp:,}（×{gp/gpb:.3f}）")
    print(f"    引き分けに必要なCVR変化  {need:+.1%}")
    print(f"    弾力性から見込まれる変化  {exp:+.1%}")
    print(f"    → {'足りない（やらない）' if exp < need else '足りる（やる価値あり）'}")

print('\n■ 7日テスト（日予算7,000円・週49,000円）の見通し')
print(f"  {'シナリオ':<28}{'CPA':>8}{'注文':>7}{'個':>7}{'粗利':>10}{'7日利益':>10}")
for p in (5980, 6980, 7980):
    gp = p - COST
    for lbl, cpa in [('3月の再現（CPA 1,880円）', 1880), ('4月の再現（2,847円）', 2847),
                     ('5月後半の再現（5,298円）', 5298)]:
        o = 49000 / cpa; q = o * 1.05
        print(f"  {p:,}円 {lbl:<20}{cpa:>8,}{o:>7.1f}{q:>7.1f}{gp*q:>10,.0f}{gp*q-49000:>+10,.0f}")
    print()
