# -*- coding: utf-8 -*-
"""新商品テスト②: 高吸水・速乾ヘアドライタオル（2026-08-16 出稿開始・ユーザー実施）

スペック = Shopify実測（graphql_query で unitCost を直読）
ベンチマーク = 既存20商品の Meta実測（8/09-15）× Shopify実測注文数
判定ラインは SKILL H節「合格ラインは価格から逆算する」に従って売価から作る。
"""
PRICE, COST = 3980, 985                     # Shopify実測（3色とも同一原価）
BUDGET = 8000                               # ユーザー申告（Meta未検証・Supermetrics停止中）
gm = 1 - COST / PRICE                       # 粗利率
gp1 = PRICE - COST                          # 粗利/個 ＝ 分岐CPA
print('■ ① スペック（Shopify実測）')
print(f'  売価 {PRICE:,}円 / 原価 {COST:,}円 / 原価率 {COST/PRICE:.2%} / 粗利率 {gm:.2%}')
print(f'  粗利/個（＝分岐CPA） {gp1:,}円')
print(f'  分岐MER {1/gm:.3f} / 目標MER（利益率35%） {1/(gm-0.35):.3f}')
print(f'  目標CPA（利益率35%・点数1.00） {PRICE*(gm-0.35):,.0f}円')

print('\n■ ② 選定基準との照合（SKILL 3166行〜・H節）')
for lbl, ok, note in [
    ('価格帯', PRICE in (3980, 4980), f'{PRICE:,}円 ＝ 実測CVR最高帯（3,980円 4.06%／4,980円 3.81%）'),
    ('原価率32%以下', COST / PRICE <= 0.32, f'{COST/PRICE:.1%}（成功組の中央値32.3%・45%以上は全滅ゾーン）'),
    ('粗利/個 3,000円以上', gp1 >= 3000, f'{gp1:,}円（基準3,000円にわずかに届かない。成功組の最低はW固定2,798円）'),
    ('PSE（電気用品安全法）', True, '非電気製品 → 対象外。秋冬の品揃え制約に引っかからない'),
    ('季節', True, 'お風呂上がり＝通年〜秋冬寄り。夏カテゴリの穴埋めとして方向は正しい'),
]:
    print(f'  {"✅" if ok else "⚠️"} {lbl:<18}{note}')

print('\n■ ③ RPM/CPM 判別式（必要 CTR×CVR = CPM ÷ (粗利/注文 × 1000)）')
# 自店の現在地（8/09-15 実測・CTR は Meta / CVR は Shopify注文÷Metaクリック）
CUR = {'ナノガラス脱毛パッド':(1622,.0257,.0326),'W固定スマホ車載ホルダー':(1432,.0291,.0311),
 '害虫ブロッカー':(2140,.0199,.0313),'形状記憶日傘':(3248,.0380,.0230),'接触冷感UVパーカー':(2951,.0310,.0367),
 'ムダ毛シェーバー':(1208,.0125,.0304),'2WAYシートボックス':(2363,.0286,.0320),'4WAY':(4261,.0312,.0388),
 '偏光・調光サングラス':(2268,.0281,.0303),'完全遮光・接触冷感UVハット':(3823,.0515,.0353),
 '完全遮光・形状記憶':(3994,.0452,.0189),'姿勢サポートチェア':(1272,.0187,.0233),
 '5WAY腰掛けファン':(2972,.0398,.0194),'接触冷感UVアームカバー':(4241,.0326,.0606),
 '快適マジックインソール':(2140,.0319,.0314),'卓上冷感クーラー':(2381,.0377,.0169),
 'バランスケアスリッパ':(1321,.0160,.0306),'携帯電動シェーバー':(2693,.0230,.0417),
 'ナノバブルシャワーヘッド':(3109,.0588,.0171),'瞬間冷感ポンチョ':(4456,.0344,.0123)}
rp = sorted(c * v * 10000 for _, c, v in CUR.values())
med = (rp[len(rp)//2 - 1] + rp[len(rp)//2]) / 2
print(f'  自店の CTR×CVR（8/09-15 実測20商品）: 中央値 {med:.2f}‱ / 最小 {rp[0]:.2f} / 最大 {rp[-1]:.2f}')
print('  ※ SKILL記載の中央値13.53‱は7月時点。夏商材の減衰で下がっているので、現在地で判定する。')
print(f'\n  {"想定CPM":>9}{"分岐(倍率1.0)":>14}{"合格(倍率2.0)":>14}   中央値{med:.1f}‱ との関係')
for lbl, cpm in [('ナノガラス級', 1622), ('ムダ毛級', 1208), ('全店中央値級', 2381),
                 ('携帯シェーバー級', 2693), ('ナノバブル級', 3109)]:
    for q in (1.20,):
        gpo = gp1 * q
        be = cpm / (gpo * 1000) * 10000; pa = be * 2
        v = '✅中央値で合格' if pa <= med else ('🟡中央値で分岐は超える' if be <= med else '🚨中央値でも分岐割れ')
        print(f'  {lbl:<10}{cpm:>7,}{be:>14.2f}{pa:>14.2f}   {v}')
print(f'  ※ 粗利/注文は 点数1.20 の前提（{gp1:,}×1.20 = {gp1*1.20:,.0f}円）。点数1.00なら必要値は1.2倍になる。')
print('  → 勝敗を分けるのは CPM。2,400円以下に収まるかを 8/18 に測る。')

print('\n■ ④ 判定ライン（SKILL H節「合格ラインは価格から逆算する」）')
for q in (1.00, 1.20):
    gpo = gp1 * q
    print(f'  点数/注文 {q:.2f} → 粗利/注文 {gpo:,.0f}円  '
          f'合格CPA(倍率2.0) {gpo/2:,.0f}円 / 最低CPA(倍率1.3) {gpo/1.3:,.0f}円 / 分岐CPA {gpo:,.0f}円')

print('\n■ ⑤ 出稿計画と到達見込み（日予算8,000円）')
for cpc in (55, 70, 90):
    for d, lbl in ((3, '中間 8/18'), (7, '本判定 8/22')):
        sp = BUDGET * d; ck = sp / cpc
        print(f'  CPC {cpc}円想定 → {lbl}: 消化 {sp:,}円 / クリック 約{ck:,.0f} '
              f'/ CVR3.0%なら注文 約{ck*0.03:.0f}件 / CPA 約{sp/(ck*0.03):,.0f}円')
    break
print('  ※ 美容帯のCPC実測: ナノバブル53円 / ナノガラス63円 / 携帯電動シェーバー117円')
ck3 = BUDGET * 3 / 63
print(f'  → CPC63円（ナノガラス級）なら3日で約{ck3:,.0f}クリック。'
      f'判定延期ライン（100クリック未満）は十分クリアする見込み。')
n50 = 50 * (gp1 * 1.20 / 2)   # 合格CPAで50件を集めるのに必要な広告費
print(f'  購入50件到達（SKILL: 新商品は50件まで確定判断を保留）: '
      f'合格CPA {gp1*1.2/2:,.0f}円なら {n50:,.0f}円 ＝ 日8,000円で約{n50/BUDGET:.0f}日 → 8/{16+round(n50/BUDGET)}頃')
