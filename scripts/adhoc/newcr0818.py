for n, c, i, cpm, ctr, ck, p, fq in CASES:
    print(f'  {n:<28}{c:>9,}{cpm:>8,.0f}{ctr:>8.2%}{c/ck:>7.0f}{p/ck:>8.2%}{c/p:>8,.0f}{fq:>6.2f}')
for a, b, lbl in [(0, 1, 'ナノガラス'), (2, 3, '害虫ブロッカー')]:
    A, B = CASES[a], CASES[b]
    ca, cb = A[1]/A[6], B[1]/B[6]
    va, vb = A[6]/A[5], B[6]/B[5]
    print(f'\n  {lbl}: CTR {B[4]/A[4]-1:+.1%} / CPC {(B[1]/B[5])/(A[1]/A[5])-1:+.1%} / '
          f'**CVR {vb/va-1:+.1%}** / **CPA {cb/ca-1:+.1%}**')

print('\n■ ② 既存セットに新素材を足した1件（バランスケアスリッパ・7/25-8/17・広告別）')
