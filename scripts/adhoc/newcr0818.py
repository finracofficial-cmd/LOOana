print('\n■ ⑥ その −9,000 は利益にどう効くか（頑健性チェック）')
ns, k, ad = 1213502, 233880, 557627
gm = 1 - k/ns; mer = ns/ad
print(f'  ナノガラス7日: 実売 {ns:,} / 原価 {k:,} / 広告 {ad:,} / MER {mer:.2f} / 粗利率 {gm:.1%}')
for x in (0.6, 0.7, 0.8):
    print(f'    限界MER = 平均×{x} = {mer*x:.2f} → 削減1円あたり利益 {1-mer*x*gm:+.3f}')
print(f'  → **3端すべて負＝削ると利益が減る。** −9,000×7 = −63,000円/週 の削減に対し、')
for x in (0.6, 0.7, 0.8):
    print(f'     ×{x}: 週 {63000*(1-mer*x*gm):+,.0f}円')
print('     中央値(×0.7)で **週 −14,474円**。セット２単独で計算しても3端すべて負（−0.026/−0.196/−0.371）。')

print('\n■ ⑦ 正しい打ち手（ナノガラス）')
