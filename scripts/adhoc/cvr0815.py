print(f"  実売 {NET7:,.0f}円 / 原価 {COST7:,.0f}円（原価率 {CR:.1%}）/ 決済手数料 {FEE:.3%}")
print(f"  購入完了セッション {sess_cp:,} → セッション単価 {AOV:,.0f}円")
print(f"  増えた売上には広告費が1円も乗らないので、"
      f"手取りは売上 × {1-CR-FEE:.3f}")
