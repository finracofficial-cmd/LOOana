def decomp(a, b, label):
    """CVRの変化を3段の掛け算に分解する（対数寄与）。"""
    (sa, ca, ka, pa), (sb, cb, kb, pb) = a, b
    r = [(cb/sb)/(ca/sa), (kb/cb)/(ka/ca), (pb/kb)/(pa/ka)]
    L = [math.log(x) for x in r]; T = sum(L)
    print(f"\n  {label}")
    print(f"    CVR {pa/sa:.3%} → {pb/sb:.3%}（{(pb/sb)/(pa/sa)-1:+.1%}）")
    for nm, x, l in zip(['カート追加率', 'カート→レジ  ', 'レジ→購入完了'], r, L):
        print(f"    {nm}  {x-1:>+7.1%}   悪化への寄与 {l/T:>6.1%}")

