# -*- coding: utf-8 -*-
"""「既存セットに足す」vs「新規セットで独立」── どちらがCPAを下げるか

⚠️ 購入数は Meta計上（広告セット単位はShopifyで分解できないため）。
   同一商品内の相対比較にのみ使う。商品全体の損益は Shopify実測が正。
"""
print('■ ① 新セットを足す前後（同一商品・14日ずつ・Meta実測）')
print('   害虫ブロッカー: 7/19に「０７１９」を新設 ／ ナノガラス: 7/22に「セット３」を新設')
print(f'  {"":<20}{"消化":>11}{"リーチ":>10}{"CTR":>8}{"クリック":>9}{"購入*":>7}{"CPA*":>8}')
BEF = [('害虫 7/05-18（1セット）', 820805, 309012, .0382, 13970, 421),
       ('ナノガラス 7/05-18（1セット）', 699979, 365916, .0287, 12346, 430)]
AFT = [('害虫 7/19-8/01（2セット）', 1032344, 375561, .0268, 12146, 351),
       ('ナノガラス 7/19-8/01（2セット）', 861696, 368571, .0282, 13680, 473)]
for b, a in zip(BEF, AFT):
    for n, c, r, ctr, ck, p in (b, a):
        print(f'  {n:<20}{c:>11,}{r:>10,}{ctr:>8.2%}{ck:>9,}{p:>7}{c/p:>8,.0f}')
    dc, dp = a[1]-b[1], a[5]-b[5]
    print(f'    → 消化 {a[1]/b[1]-1:+.1%} / 購入 {a[5]/b[5]-1:+.1%} / '
          f'**ブレンドCPA {(a[1]/a[5])/(b[1]/b[5])-1:+.1%}** / '
          f'増分CPA {"算出不能（購入が減った）" if dp<=0 else f"{dc/dp:,.0f}円"}\n')
print('  ⚠️ この窓は予算の増額とも重なっている（害虫は7月下旬に4.31倍へ増額）。')
print('     「セットを増やしたから」と「予算を増やしたから」は分離できていない。断定しない。')

print('■ ② 分離できる比較 ── 同じ期間・同じ商品の2セットを並べる（7日 8/11-17）')
print(f'  {"":<26}{"消化":>9}{"CTR":>8}{"CVR*":>8}{"CPA*":>8}')
for n, c, ck, p, ctr in [('ナノガラス セット２（既存）', 460730, 7675, 220, .0263),
                          ('ナノガラス セット３（新設）',  97061, 1193,  59, .0221),
                          ('害虫 本体（既存）',           97455,  850,  22, .0185),
                          ('害虫 ０７１９（新設）',        81771,  784,  27, .0213)]:
    print(f'  {n:<26}{c:>9,}{ctr:>8.2%}{p/ck:>8.2%}{c/p:>8,.0f}')
print('  → **新セット単体のCPAは既存より 21〜32% 安い。**（同一期間なので交絡なし）')
print('     しかも CVR が +33〜72% 違う ＝ **同じ人に出していない。別の層を掘っている。**')

print('\n■ ③ この2つを合わせると何が言えるか')
print('  ・新セット単体は安い（②・交絡なし）')
print('  ・合計のCPAは上がる（①・交絡ありだが方向は一貫）')
print('  → **新セットは「同じ予算でCPAを下げる」手段ではない。**')
print('     「予算を増やしたときの悪化を和らげる」手段。')
print('     量を増やせば確度ランキングを下へ降りるという構造は変わらない。')

print('\n■ ④ 「量を固定してCPAを下げる」唯一の実例（予算を1円も増やしていない）')
print('  バランスケアスリッパ: 日予算5,000円のまま素材Dを既存セットへ追加（8/07）')
print(f'  {"広告":<12}{"消化":>9}{"CPM":>8}{"CTR":>8}{"CVR*":>8}{"CPA*":>8}')
for n, c, cpm, ctr, ck, p in [('A（既存）', 68159, 1858.2, .0205, 751, 19),
                               ('D（新素材）', 51218, 1385.3, .0167, 618, 21)]:
    print(f'  {n:<12}{c:>9,}{cpm:>8,.0f}{ctr:>8.2%}{p/ck:>8.2%}{c/p:>8,.0f}')
print('  → CPA −32.0%。**予算据え置きで効率だけ上がった。**')
print('     週次MERも 6/29週 1.60 → 8/10週 2.23 に改善（Shopify実測）。')

print('\n■ ⑤ 「CPAを安くして大量に売る」の答え ── 商品を増やすのが唯一')
print('   同じ商品の量を増やすと必ずランキングを下へ降りる。商品が違えばプールが違う。')
print(f'  {"":<30}{"増分MER":>12}{"分岐1.40との差":>16}')
OLD = [('害虫（増額）', 0.14), ('4WAY（増額）', -0.76), ('パーカー（増額）', -0.80),
       ('ナノガラス（増額）', -1.64), ('3WAY（増額）', -2.76), ('サングラス（増額）', -2.94)]
NEW = [('ムダ毛（新商品）', 4.50), ('5WAY（新商品）', 4.45), ('ポンチョ（新商品）', 2.95),
       ('卓上（新商品）', 2.19), ('携帯シェーバー（新商品）', 2.16), ('アームカバー（新商品）', 1.56)]
for lbl, arr in [('【既存主力を増額】', OLD), ('【新商品を追加】', NEW)]:
    print(f'  {lbl}')
    for n, m in arr:
        print(f'    {n:<28}{m:>12.2f}{m-1.40:>+16.2f}')
print('  → **既存の増額は6件中6件が分岐割れ。新商品は6件中6件が分岐超え。例外ゼロ。**')

print('\n■ ⑥ 使い分けの結論')
print('  ① 量を変えずにCPAを下げたい  → **既存セットに新素材を追加**（スリッパD型）')
print('     失敗コストは小さい（Metaが選ばなければ配信されない＝害虫の秋CRは1.2%）')
print('     ただし日予算の大きい商品では探索期の損が大きい（4WAYは3日87,000円）')
print('     → **日予算の小さい商品から試す。**')
print('  ② 量を増やしたい            → **新規セット**（配信枠が増えるのはこれだけ）')
print('     コスト: 学習3〜6日でCPMがピーク＋自社競合（日傘で+23〜33%）')
print('     ブレンドCPAは上がる前提で、増分CPAが分岐CPAを下回るかで判定する')
print('  ③ CPAを保ったまま大量に売りたい → **商品を増やす**。①②では両立しない')
