D = [f'2026-08-{i:02d}' for i in range(1, 15)]
S = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
for r in csv.DictReader(open('data/daily/daily_sales.csv', encoding='utf-8')):
    S[r['name']][r['date']][0] += int(r['gross']); S[r['name']][r['date']][1] += int(r['disc'])
AD = collections.defaultdict(lambda: collections.defaultdict(float))
for r in csv.DictReader(open('data/daily/daily_ad.csv', encoding='utf-8')):
    AD[r['campaign']][r['date']] += float(r['cost'])

rows = []
for n, (od, g_q) in Q.items():
    g = sum(S[n][d][0] for d in D if d in S[n])
    assert g == g_q, f'{n}: 日次CSV {g:,} ≠ ShopifyQL転記 {g_q:,}'     # 転記の検算
    dc = sum(S[n][d][1] for d in D if d in S[n])
    c = sum(AD[MAP.get(n, n)].get(d, 0) for d in D)
    if c < 30000: continue                       # 広告費が小さすぎる商品は倍率が暴れるので除く
    q = round(g / PRICE[n])
    gp_ord = (PRICE[n] - COST[n]) * q / od       # 粗利/注文 = 粗利/個 × 点数/注文
    cpa = c / od
    rows.append(dict(n=n, cat=cat(n), p=PRICE[n], rate=COST[n]/PRICE[n], ipo=q/od,
                     gp=gp_ord, cpa=cpa, mult=gp_ord/cpa, net=g-dc, ad=c,
                     prof=(g-dc)-q*COST[n]-c))
print('\n■ ④ いま動いている商品を「倍率」で並べる（8/01-14実測・広告費3万円以上）')
print('   倍率 = 粗利/注文 ÷ CPA(注文)。2.0超は全勝、1.3以下は全負け。')
print(f"  {'商品':<24}{'季':<4}{'売価':>6}{'原価率':>7}{'点/注':>6}{'粗利/注文':>10}{'CPA':>8}{'倍率':>7}{'利益':>11}")
for r in sorted(rows, key=lambda x: -x['mult']):
    mark = '◎' if r['mult'] >= 2.0 else ('△' if r['mult'] >= 1.3 else '✕')
    print(f"  {r['n']:<24}{r['cat']:<4}{r['p']:>6,}{r['rate']:>7.1%}{r['ipo']:>6.2f}"
          f"{r['gp']:>10,.0f}{r['cpa']:>8,.0f}{r['mult']:>6.2f}{mark}{r['prof']:>+11,.0f}")

win = [r for r in rows if r['mult'] >= 2.0]; lose = [r for r in rows if r['mult'] < 1.3]
print(f"\n  勝ち{len(win)}品のCPA中央帯 {min(r['cpa'] for r in win):,.0f}〜{max(r['cpa'] for r in win):,.0f}円"
      f" / 原価率 {min(r['rate'] for r in win):.0%}〜{max(r['rate'] for r in win):.0%}")
print(f"  負け{len(lose)}品のCPA         {min(r['cpa'] for r in lose):,.0f}〜{max(r['cpa'] for r in lose):,.0f}円"
      f" / 原価率 {min(r['rate'] for r in lose):.0%}〜{max(r['rate'] for r in lose):.0%}")
print('  → 原価率は勝ち負けを分けていない。分けているのはCPA、つまり「その商品を欲しい人がどれだけ広いか」。')

