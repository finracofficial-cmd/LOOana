REMEDY_SHORT = {'素材疲弊':'新CR or 複製リセット','頻度過多':'オーディエンス拡大',
 'LP/オファー':'LP・オファー改善','CPM上昇':'全開放/訴求替え','需要減衰':'減額'}

def judge(p):
    t = []
    if not p.get('判定日'):
        return f"S-1:本日は判定日ではない（次回 {p.get('次回判定日','未設定')}）", "👀 据置（監視のみ）", p['予算']
    guard = p.get('P1警戒') or p.get('P1凍結')   # P1凍結は旧名（後方互換）
    if guard:
        t.append(f"P-1:{p.get('P1理由','全店の週次MERが悪化')}→未測定のままの増額を禁止（増分MERが目標超えの増額のみ許可）")
    t.append("S-1:本日が判定日")
    t.append(f"S0:日販{p['日販']:.1f}個" + ("（<10 利益率は参考値扱い）" if p['日販'] < 10 else ""))
    if p['利益7'] <= 0:
        t.append(f"S1:7日利益{p['利益7']:+,.0f}円→マイナス")
        if p['赤字比率'] >= 0.15 or p['2巡目']:
            t.append(f"S1a:日次赤字が予算の{p['赤字比率']*100:.0f}%" + ("・2巡目" if p['2巡目'] else "") + "→半減")
            return " → ".join(t), "🚨 予算半減＋テコ入れ", int(p['予算']*0.5)
        t.append(f"S1a:日次赤字が予算の{p['赤字比率']*100:.0f}%（<15%）")
        return " → ".join(t), "🔧 据置＋CR追加(7日後判定)", p['予算']
    t.append(f"S1:7日利益+{p['利益7']:,.0f}円→黒字")
    ebr = p['分岐']   # 2026-07-28ユーザー確定: MER・分岐・目標はすべて手数料控除前で統一（手数料は全体サマリーで把握）
    # S1b は「増額分が赤字だったか」の安全弁。2手法の結論がゾーンをまたいで割れている場合も、
    # 悪い方（下限）で判定できるならそれを使う（下限が分岐を超えていれば増額が赤字でないことは確定する）
    im_safety = p['増分MER'] if p['増分MER'] is not None else p.get('増分MER下限')
    if im_safety is not None and p.get('実験有効', True):
        im0 = im_safety; dirn = p.get('変更方向', '増額')
        if dirn == '増額':
            if im0 < ebr:
                t.append(f"S1b:増額分の増分MER {im0:+.2f} < 分岐 {ebr:.2f}→増やした分だけが赤字")
                return " → ".join(t), "🚨 元の予算に戻す", p.get('元予算') or int(p['予算']*0.8)
            t.append(f"S1b:増額分の増分MER {im0:+.2f} ≥ 分岐 {ebr:.2f}→増額分は黒字")
        else:
            if im0 >= p['目標MER']:
                t.append(f"S1b:削った分の増分MER {im0:+.2f} ≥ 目標 {p['目標MER']:.2f}→削った分は稼いでいた")
                return " → ".join(t), "🚨 減額を取り消す（元の予算に戻す）", p.get('元予算') or int(p['予算']*1.25)
            t.append(f"S1b:削った分の増分MER {im0:+.2f} < 目標→減額は正解")
    if p['MER'] < p['目標MER']:
        t.append(f"S2:MER {p['MER']:.2f} < 目標 {p['目標MER']:.2f}")
        if p['MER'] - ebr <= 0:
            t.append(f"S2a:余裕{p['MER']-ebr:+.2f}≤0→減額")
            return " → ".join(t), "🔧 減額", int(p['予算']*0.7)
        t.append(f"S2a:余裕{p['MER']-ebr:+.2f}>0")
        # S2c（2026-07-30追加）: 平均MERが目標未達でも、追加1円の成績（実測の増分MER）が目標を超えていて
        # 枠で止まっているなら増額する。予算の増減は平均ではなく限界で決めるという原則（7c）の徹底。
        # これを入れないと「平均MERが目標をわずかに下回る商品」がS2a→S2bへ逸れてS5に到達せず、
        # 増分MERが目標を大きく超えていても増額されない（2026-07-30に5WAY腰掛けファンで発覚）。
        if p['増分MER'] is not None and p['増分MER'] >= p['目標MER'] and p['消化率'] >= 0.95:
            t.append(f"S2c:平均MERは目標未達だが実測の増分MER {p['増分MER']:+.2f} ≥ 目標{p['目標MER']:.2f}・"
                     f"消化率{p['消化率']*100:.0f}%≥95%→追加1円は目標を超えている")
            return " → ".join(t), "🚀 +20〜30%増額（限界が目標超え）", int(p['予算']*1.25)
        if p.get('転用が有利'):
            t.append(f"S2b:転用先{p.get('転用先','')}の実測増分MER {p.get('転用増分MER',0):.2f}で"
                     f"{p['転用利益']:+,.0f}円/日 > 現状{p['利益7']/7:+,.0f}円/日→転用")
            return " → ".join(t), "🔄 停止して予算を転用", 0
        t.append(f"S2b:{p.get('転用不可理由','転用しても改善しない')}→維持")
        return " → ".join(t), "✅ 維持（CR/LP/価格で手当て）", p['予算']
    t.append(f"S2:MER {p['MER']:.2f} ≥ 目標 {p['目標MER']:.2f}→効率OK")
    if p['消化率'] < 0.95:
        t.append(f"S3:消化率{p['消化率']*100:.0f}%<95%→枠に余裕あり")
        return " → ".join(t), "✅ 据置（増額しても消化できない）", p['予算']
    t.append(f"S3:消化率{p['消化率']*100:.0f}%≥95%→枠で止まっている")
    if p['増分MER'] is None:
        if p.get('増分MER両論'):
            t.append(f"S4:増分MER測定済だが2手法が {p.get('増分MER下限',0):+.2f}／{p.get('増分MER上限',0):+.2f} と"
                     f"分岐{ebr:.2f}〜目標{p['目標MER']:.2f}をまたぎ結論が割れる→増額しない")
            return " → ".join(t), "🟡 据置（増分MERの結論が割れる→次回判定へ延期）", p['予算']
        t.append("S4:増分MER未測定")
        if guard:
            t.append("P-1発動中のため未測定の増額は禁止→据置。次に予算を動かすときに±25%以上動かして測定可能にする")
            return " → ".join(t), "🧊 据置（P-1発動中・未測定の増額は禁止）", p['予算']
        return " → ".join(t), "🚀 +25%増額（測定も兼ねる）", int(p['予算']*1.25)
    im = p['増分MER']
    t.append(f"S4:増分MER測定済 {im:+.2f}")
    if im >= p['目標MER']:
        msg = f"S5:{im:.2f} ≥ 目標{p['目標MER']:.2f}"
        if guard: msg += "（P-1発動中だが実測の増分MERが目標超えなので増額を許可）"
        t.append(msg)
        return " → ".join(t), "🚀 +20〜30%増額", int(p['予算']*1.25)
    if im >= ebr:
        t.append(f"S5:分岐{ebr:.2f} ≤ {im:.2f} < 目標{p['目標MER']:.2f}")
        return " → ".join(t), "🟡 据置（利益は増えるが率が下がる）", p['予算']
    t.append(f"S5:{im:.2f} < 分岐{ebr:.2f}→増額分が赤字")
    return " → ".join(t), "🚨 元の予算に戻す", p.get('元予算') or int(p['予算']*0.8)
