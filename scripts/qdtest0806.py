#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""2026-08-06 数量割引コンテンツのA/Bテスト設計
7日実測(7/30-8/05)の点数/注文で、テスト群・対照群を選ぶ"""
# (商品, 7日個数, 7日注文, 実売, 原価/個, 単価)
D=[('ナノガラス脱毛パッド',333,316,1311609,751,3980),('4WAY',233,176,1101327,1730,4980),
('害虫ブロッカー',242,143,881570,867,3980),('形状記憶日傘',170,147,822945,1309,4980),
('接触冷感UVパーカー',153,135,594015,1434,3980),('完全遮光・形状記憶',104,94,507462,1309,4980),
('ムダ毛シェーバー',67,67,467660,2798,6980),('5WAY腰掛けファン',84,65,398898,1848,4980),
('卓上冷感クーラー',57,51,333684,1996,5980),('偏光・調光サングラス',68,62,265864,893,3980),
('瞬間冷感ポンチョ',44,26,161588,987,3980),('W固定スマホ車載ホルダー',41,37,159996,1182,3980),
('接触冷感UVアームカバー',41,36,159200,784,3980),('完全遮光・接触冷感UVハット',18,16,87399,1411,4980)]
print('='*112)
print('■ 7日実測（7/30-8/05）の点数/注文 — 伸び余地の大きい順')
print('='*112)
print(f"{'商品':<22}{'個数':>6}{'注文':>6}{'点数/注文':>10}{'実売':>10}{'粗利/個':>8}{'+0.2で増える粗利/週':>20}")
rows=[]
for n,it,o,s,c,p in D:
    r=it/o; gp=s/it-c
    gain=o*0.2*gp*0.9   # 0.2個/注文の増加。追加分は10-15%割引が乗るので0.9掛け
    rows.append((n,it,o,r,s,gp,gain))
for n,it,o,r,s,gp,gain in sorted(rows,key=lambda x:-x[6]):
    print(f'{n:<22}{it:>6}{o:>6}{r:>10.2f}{s:>10,}{gp:>8,.0f}{gain:>+20,.0f}')
print()
print('='*112)
print('■ テスト設計（差分の差分で測る）')
print('='*112)
T=['ナノガラス脱毛パッド','害虫ブロッカー','4WAY','形状記憶日傘']
C=['接触冷感UVパーカー','完全遮光・形状記憶','偏光・調光サングラス','5WAY腰掛けファン','卓上冷感クーラー']
def agg(names):
    it=sum(x[1] for x in D if x[0] in names); o=sum(x[2] for x in D if x[0] in names)
    s=sum(x[3] for x in D if x[0] in names)
    return it,o,it/o,s
ti,to,tr,ts=agg(T); ci,co,cr,cs=agg(C)
print(f'  テスト群（記載を入れる）4商品: {"／".join(T)}')
print(f'    7日 {ti}個 / {to}注文 = 点数/注文 {tr:.3f} ／ 実売 {ts:,}円')
print(f'  対照群（触らない）5商品: {"／".join(C)}')
print(f'    7日 {ci}個 / {co}注文 = 点数/注文 {cr:.3f} ／ 実売 {cs:,}円')
print()
print('  ★ 形状記憶日傘（テスト）と 完全遮光日傘（対照）は同一SKU・同一価格・同一4色。')
print('    ページ以外の変数が完全に揃っているので、これだけで最もクリーンなA/Bになる。')
print()
gain=sum(x[6] for x in rows if x[0] in T)
print(f'  期待効果: テスト群の点数/注文が +0.2 なら 粗利 +{gain:,.0f}円/週')
print(f'  全商品に展開できれば +{sum(x[6] for x in rows):,.0f}円/週')
print()
print('='*112)
print('■ 判定（8/13・実施+7日）')
print('='*112)
print(f'  KPI = 点数/注文（値引率を補助指標に併読）')
print(f'  合格: テスト群の点数/注文の上昇 − 対照群の上昇 ≥ +0.10')
print(f'    → 全商品へ展開')
print(f'  引き分け: 差が +0.03〜+0.10 → テスト群のみ継続、記載位置と文言を変えて再テスト')
print(f'  不合格: 差が +0.03未満 → 記載を撤去（ページの情報量を増やす副作用があるため）')
print()
print('  ⚠️ 交絡に注意: 同期間に 4WAY(37,500)・卓上(7,500)・携帯(8,250) の減額が走っている。')
print('     予算変更は「注文数」を動かすが「点数/注文」は動かしにくいので、KPIとしては比較的頑健。')
print('     ただし流入の質が変わると点数/注文も動くため、対照群との差分で見ることが必須。')
