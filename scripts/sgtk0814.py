def show(name,rows,price,cost,be,tg):
    gp=price-cost
    print(f"\n■ {name}  売価{price:,} 原価{cost:,} 粗利{gp:,} 分岐MER {be} 目標MER {tg}")
    print(f"  {'日':7}{'広告費':>8}{'CTR':>7}{'CPM':>7}{'クリック':>7}{'注文':>5}{'CVR':>7}{'売上':>9}{'MER':>6}{'利益':>9}{'売上/CL':>8}")
    for d,ad,im,ck,o,g in rows:
        q=round(g/price); pr=g-q*cost-ad
        print(f"  {d:7}{ad:8,}{ck/im*100:6.2f}%{ad/im*1000:7,.0f}{ck:7}{o:5}{o/ck*100 if ck else 0:6.2f}%{g:9,}{g/ad:6.2f}{pr:9,.0f}{g/ck:8.0f}")
    for lbl,sl in [('直近3日',rows[-3:]),('直近7日',rows[-7:]),('その前7日',rows[-14:-7])]:
        ad=sum(r[1] for r in sl); im=sum(r[2] for r in sl); ck=sum(r[3] for r in sl)
        o=sum(r[4] for r in sl); g=sum(r[5] for r in sl); q=round(g/price)
        print(f"  {lbl:9} 広告{ad:>8,} CTR {ck/im*100:5.2f}% CPM {ad/im*1000:5,.0f} クリック{ck:>5} 注文{o:>4} "
              f"CVR {o/ck*100 if ck else 0:5.2f}% 売上{g:>9,} MER {g/ad:5.2f} 利益{g-q*cost-ad:>9,.0f} 売上/CL {g/ck if ck else 0:4.0f}円")
