def agg(W):
    o=sum(a for a,b in W.values()); i=sum(b for a,b in W.values()); return o,i
o1,i1=agg(W1); o4,i4=agg(W4)
r1,r4=i1/o1, i4/o4
print(f"点数/Σ商品orders  7/15-21={r1:.4f}  8/05-11={r4:.4f}  差={r4-r1:+.4f}")
# シフトシェア: 共通商品はW1性向、新規はW4性向で代替（新規はミックス効果側に寄与）
keys=set(W1)|set(W4)
mix=0.0; prop=0.0
for k in keys:
    w1=W1[k][0]/o1 if k in W1 else 0.0
    w4=W4[k][0]/o4 if k in W4 else 0.0
    p1=W1[k][1]/W1[k][0] if k in W1 else W4[k][1]/W4[k][0]
    p4=W4[k][1]/W4[k][0] if k in W4 else p1
    mix += (w4-w1)*p1
    prop += w4*(p4-p1)
print(f"  商品構成の変化(ミックス効果) = {mix:+.4f}")
print(f"  各商品の複数買い性向の変化   = {prop:+.4f}")
print(f"  合計 = {mix+prop:+.4f}")
