"""「値上げが怖い」を実測で検証する。当店の値上げ・値下げの全実績と、最悪ケースの下振れ額。"""
print("■ ① 当店が実際にやった価格変更の全記録（Shopify実測）")
print(f"{'商品':16}{'変更':>18}{'幅':>8}{'前の日販':>9}{'後の日販':>9}{'結果':>8}")
H=[('ムダ毛シェーバー','5,980→6,980','+16.7%',5.6,7.7,'✅ 増えた'),
   ('3WAYサーキュレーター','5,980→6,980','+16.7%',6.6,5.7,'✅ 基準通過'),
   ('完全遮光UVハット','5,980→4,980','−16.7%',None,None,'（値下げ）'),
   ('姿勢サポートチェア','7,980→5,980','−25.1%',2.8,2.9,'❌ 値下げ失敗'),
   ('接触冷感UVパーカー','3,980→4,980','+25.1%',None,None,'⏳ 8/20判定')]
for n,c,w,a,b,r in H:
    aa=f"{a:.1f}個" if a else "—"; bb=f"{b:.1f}個" if b else "—"
    print(f"{n:16}{c:>18}{w:>8}{aa:>9}{bb:>9}{r:>8}")
print("\n  → 値上げは2回とも成功。値下げは1回やって失敗している。")

print("\n■ ② 姿勢サポートチェアの値下げは「もう実験して外れている」")
print(f"  {'':22}{'7,980円(3-5月)':>16}{'5,980円(8/04-13)':>18}")
print(f"  {'稼働':22}{'54日・152件':>16}{'10日・29件':>18}")
print(f"  {'CVR':22}{'2.13%':>16}{'2.29%':>18}")
print(f"  {'CPA(注文)':22}{'3,474円':>16}{'3,154円':>18}")
print(f"  {'粗利/個':22}{'6,169円':>16}{'4,169円':>18}")
print(f"  {'1件あたり利益':22}{'+2,695円':>16}{'+1,015円':>18}")
print("  値下げで引き分けにするには CVR +48%（2.13→3.15%）が必要だった。実測は +7.5% だけ。")
print("  → 7,980円へ戻すのは『値上げ』ではなく『失敗した値下げの巻き戻し』。")

print("\n■ ③ 最悪ケースの下振れ額（7日で判定 → 1クリックで戻せる）")
q,gp_old,gp_new,ad,now = 29, 4169, 6169, 69393, 42837
print(f"  現状（5,980円）: 販売{q}個 × 粗利{gp_old:,} − 広告{ad:,} = 利益 {now:,}円/週")
for d in (0,0.164,0.324,0.50,0.612,0.80):
    nq=q*(1-d); pf=nq*gp_new-ad
    tag=''
    if abs(d-0.164)<1e-9: tag='← 当店の実測弾力性（値下げ実験の逆）'
    if abs(d-0.324)<1e-9: tag='← ここまでは今より良い（改善ライン）'
    if abs(d-0.612)<1e-9: tag='← ここで初めて赤字（黒字化ライン）'
    print(f"    数量 −{d*100:4.1f}%  販売{nq:5.1f}個  利益 {pf:>8,.0f}円/週   今との差 {pf-now:>+8,.0f}円  {tag}")
print(f"\n  数量が半減しても週−22,780円。**7日で判定して戻すので、外したときの損失はこの1週間分だけ。**")
print(f"  当たったときの +56,260円/週 は、戻さない限り毎週入り続ける。")
print(f"  → 損失は1回きり・上限あり／利益は毎週・上限なし。賭けとして非対称。")

print("\n■ ④ 怖さを半分にする選択肢")
for p,gp in ((6980,5169),(7980,6169)):
    y=1-gp_old/gp; z=1-ad/(q*gp)
    print(f"  {p:,}円: 改善ライン {y*100:.1f}%  黒字化ライン {z*100:.1f}%  同数量なら週 +{q*(p-5980)*0.97:,.0f}円")
print("  6,980円なら上げ幅は+16.7%＝ムダ毛・3WAYで2回とも成功した実績と同じ幅。")
