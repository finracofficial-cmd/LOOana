def agg(rows):
    c=sum(x[1] for x in rows); i=sum(x[2] for x in rows); cl=sum(x[4] for x in rows); ocl=sum(x[5] for x in rows)
    g=sum(S[x[0]][0] for x in rows); s=g-sum(S[x[0]][1] for x in rows); q=round(g/3980)
    return c,i,cl,ocl,q,s
