D=['2026-08-%02d'%d for d in range(6,13)]
for n in ['害虫ブロッカー','接触冷感UVパーカー','接触冷感UVアームカバー']:
    gp=PRICE[n]-COST[n]; gr=gp/PRICE[n]
    print(f"\n■ {n}  売価{PRICE[n]:,} 原価{COST[n]:,} 粗利{gp:,}円({gr*100:.1f}%)  分岐MER {1/gr:.2f}")
    print(f"  {'日':6}{'広告費':>8}{'imp':>7}{'CTR':>7}{'CPM':>7}{'クリック':>6}{'注文':>5}{'CVR':>7}{'頻度':>6}{'売上':>9}{'MER':>6}{'利益':>9}{'粗利RPM':>8}{'判別':>6}")
    for i,d in enumerate(D):
        g,di=S[n].get(d,(0,0)); ad=AD[n][d]; im=IMP[n][i]; ck=CLK[n][i]; o=ORD[n][i]
        rev=g-di; q=round(g/PRICE[n]); c=q*COST[n]; pr=rev-c-ad
        ctr=ck/im; cvr=o/ck; cpm=ad/im*1000; rpm=ctr*cvr*gp*1000
        print(f"  {d[5:]:6}{ad:8,}{im:7,}{ctr*100:6.2f}%{cpm:7,.0f}{ck:6}{o:5}{cvr*100:6.2f}%{FRQ[n][i]:6.2f}{rev:9,}{rev/ad:6.2f}{pr:9,}{rpm:8,.0f}{rpm/cpm:6.2f}")
    G=sum(S[n].get(d,(0,0))[0] for d in D); DI=sum(S[n].get(d,(0,0))[1] for d in D)
    A=sum(AD[n].values()); IM=sum(IMP[n]); CK=sum(CLK[n]); O=sum(ORD[n])
    Q=round(G/PRICE[n]); C=Q*COST[n]; REV=G-DI
    ctr=CK/IM; cvr=O/CK; cpm=A/IM*1000; rpm=ctr*cvr*gp*1000
    print(f"  {'7日計':6}{A:8,}{IM:7,}{ctr*100:6.2f}%{cpm:7,.0f}{CK:6}{O:5}{cvr*100:6.2f}%{'':6}{REV:9,}{REV/A:6.2f}{REV-C-A:9,}{rpm:8,.0f}{rpm/cpm:6.2f}")
    need=cpm/(gp*1000)
    print(f"   → 黒字に必要な CTR×CVR = CPM {cpm:,.0f} ÷ (粗利 {gp:,} ×1000) = {need*100:.3f}%   実績 {ctr*cvr*100:.3f}%   充足率 {ctr*cvr/need*100:.0f}%")
