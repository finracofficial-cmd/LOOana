#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""2026-08-04 「どこの広告費が無駄になっているか」を商品別に特定する
売上・個数・注文は Shopify実測、広告費は Meta実測（datarules.py の分担）。
ピーク週 6/08-6/14 と 直近完全週 7/27-8/02 を比較し、商品ごとの増分MERを出す。
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from datarules import Product

COST = {'4WAY':1730,'ナノガラス':752,'形状記憶日傘':1309,'害虫':867,'パーカー':1434,
        '完全遮光日傘':1309,'サングラス':893,'ディスペンサー':2373,'3WAY':2485,
        'UV歯ブラシ':3240,'健康サンダル':1162,'スリッパ':1304,'保温プレート':3703,
        'ナノバブル':2255,'UVハット':1411,'卓上':1996,'5WAY':1848,'ムダ毛':2798,
        'ポンチョ':987,'携帯シェーバー':1743,'アームカバー':784,'ワンピース':1968,
        '車載ホルダー':1490}
SEASON = {'4WAY','形状記憶日傘','完全遮光日傘','パーカー','サングラス','3WAY','卓上',
          '5WAY','ポンチョ','アームカバー','UVハット','ワンピース','害虫'}

# (Shopify gross, items, orders, Meta cost)
P0 = {  # 2026-06-08 〜 06-14
 '4WAY':(1623480,326,242,301853),'ナノガラス':(1540260,387,362,322853),
 '形状記憶日傘':(1454160,290,254,429032),'害虫':(1042760,262,135,116825),
 'パーカー':(692520,167,155,173189),'完全遮光日傘':(562740,112,103,194852),
 'サングラス':(382080,96,84,112827),'ディスペンサー':(332020,49,31,80991),
 '3WAY':(310960,52,37,91406),'UV歯ブラシ':(251440,28,27,90237),
 '健康サンダル':(229080,46,41,91065),'スリッパ':(219120,42,38,90491),
 '保温プレート':(206770,23,16,68036),'ナノバブル':(84760,12,11,45750),
}
P1 = {  # 2026-07-27 〜 08-02
 '4WAY':(1429260,285,226,558298),'ナノガラス':(1249720,314,293,500329),
 '害虫':(1098480,275,161,504023),'形状記憶日傘':(1085640,217,186,414676),
 'パーカー':(648740,163,146,228221),'完全遮光日傘':(617520,123,109,242522),
 '5WAY':(512940,103,75,115184),'ムダ毛':(431760,62,61,95856),
 '卓上':(412620,68,61,188189),'ポンチョ':(270640,68,45,91760),
 'サングラス':(262680,66,58,153436),'3WAY':(252160,42,31,112727),
 'アームカバー':(199000,50,46,127765),'携帯シェーバー':(164340,33,33,76153),
 '健康サンダル':(134460,27,25,90827),'UV歯ブラシ':(98780,11,10,71742),
 'ディスペンサー':(47860,5,7,39550),'スリッパ':(44820,9,7,34966),
 '車載ホルダー':(39800,10,10,11911),'UVハット':(29880,6,6,17064),
}
CAT0, CAT1 = 207815, 210511          # カタログ広告（商品配賦しない）

def prod(k, t):
    g, i, o, a = t
    return Product(k, gross=g, items=i, orders=o, unit_cost=COST[k], ad_cost=a)

A = {k: prod(k, v) for k, v in P0.items()}
B = {k: prod(k, v) for k, v in P1.items()}

print('=' * 112)
print('全店（カタログ含む）— Shopify実測売上 / Meta実測広告費')
print('=' * 112)
S0 = sum(p.gross for p in A.values()); C0 = sum(p.ad_cost for p in A.values()) + CAT0
S1 = sum(p.gross for p in B.values()); C1 = sum(p.ad_cost for p in B.values()) + CAT1
G0 = sum(p.cogs for p in A.values());  G1 = sum(p.cogs for p in B.values())
print(f'{"":18}{"6/08週":>14}{"7/27週":>14}{"変化":>11}')
for lab, a, b in [('売上(gross)', S0, S1), ('原価', G0, G1), ('広告費', C0, C1),
                  ('利益', S0-G0-C0, S1-G1-C1)]:
    print(f'{lab:18}{a:14,}{b:14,}{(b/a-1)*100:+10.1f}%')
print(f'{"利益率":18}{(S0-G0-C0)/S0*100:13.1f}%{(S1-G1-C1)/S1*100:13.1f}%'
      f'{((S1-G1-C1)/S1-(S0-G0-C0)/S0)*100:+10.1f}pt')
print(f'{"原価率":18}{G0/S0*100:13.1f}%{G1/S1*100:13.1f}%')
print()
print(f'★ 広告費を {C1-C0:+,}円/週 増やして、売上は {S1-S0:+,}円/週。')
print(f'   その増分だけを取り出すと: 増えた売上 {S1-S0:,} − 増えた原価 {G1-G0:,} − 増えた広告費 {C1-C0:,}')
print(f'   = {(S1-S0)-(G1-G0)-(C1-C0):+,}円/週  →  年換算 {((S1-S0)-(G1-G0)-(C1-C0))*52:+,}円')

print()
print('=' * 112)
print('商品別: 追加した広告費1円が生んだ売上（増分MER）')
print('※ 7週間離れた比較なので、季節商品[季]は季節要因が混ざる。通年商品[通]のほうが信頼できる')
print('=' * 112)
print(f"{'商品':16}{'区':4}{'広告費6/08':>11}{'→7/27':>11}{'Δ広告費':>11}{'Δ売上':>12}{'増分MER':>9}{'Δ利益':>12}")
rows = []
for k in sorted(set(A) | set(B)):
    a = A.get(k); b = B.get(k)
    c0 = a.ad_cost if a else 0; c1 = b.ad_cost if b else 0
    s0 = a.gross if a else 0;   s1 = b.gross if b else 0
    g0 = a.cogs if a else 0;    g1 = b.cogs if b else 0
    dc, ds = c1-c0, s1-s0
    if abs(dc) < 21000:      # 週21,000円 = 日3,000円未満は測定不能（SKILL規定）
        rows.append((k, c0, c1, dc, ds, None, ds-(g1-g0)-dc)); continue
    rows.append((k, c0, c1, dc, ds, ds/dc, ds-(g1-g0)-dc))
for k, c0, c1, dc, ds, im, dp in sorted(rows, key=lambda x: (x[5] is None, x[5] or 0)):
    seg = '季' if k in SEASON else '通'
    imt = f'{im:9.2f}' if im is not None else '     測定不可'
    print(f'{k:16}{seg:4}{c0:11,}{c1:11,}{dc:+11,}{ds:+12,}{imt}{dp:+12,}')

print()
print('分岐となる増分MER = 1/(1−原価率) = {:.3f}。これを下回る増額は、追加分だけで見ると赤字。'.format(1/(1-G1/S1)))

print()
print('=' * 112)
print('保守的な見積り: 削って確実に増える利益はいくらか')
print('=' * 112)
print('「6月の売上が戻る」とは仮定しない。売上減の一部は季節・需要側の要因で、削っても戻らないため。')
print('確実に言えるのは: 増分MERが分岐(1.401)未満なら、削った分だけ利益は増える。')
print('  増える利益 = 削減額 × (1 − max(0, 実測増分MER) ÷ 1.401)')
print()
be = 1/(1-G1/S1)
cut = [(k,c0,c1,dc,ds,im,dp) for k,c0,c1,dc,ds,im,dp in rows if im is not None and dc>0 and im<be]
print(f"{'商品':16}{'区':4}{'現/週':>11}{'Δ広告費':>11}{'増分MER':>9}{'確実に増える利益':>17}")
tot_c=tot_g=0
for k,c0,c1,dc,ds,im,dp in sorted(cut,key=lambda x:-(x[3]*(1-max(0,x[5])/be))):
    g = dc*(1-max(0,im)/be); seg='季' if k in SEASON else '通'
    tot_c+=dc; tot_g+=g
    print(f'{k:16}{seg:4}{c1:11,}{dc:+11,}{im:9.2f}{g:+17,.0f}')
print('-'*112)
print(f'{"合計":20}{"":11}{tot_c:+11,}{"":9}{tot_g:+17,.0f}')
print()
print(f'6/08週の水準まで全部戻すと 週{tot_c:,}円の削減 → 確実に増える利益 {tot_g:+,.0f}円/週')
print(f'日予算では {tot_c/7:,.0f}円/日の削減。534,000 → {534000-tot_c/7:,.0f}円/日')

print()
print('=' * 112)
print('実行案: いきなり6月水準まで戻さず、測れる大きさ（各−25〜30%）で3商品だけ削る')
print('=' * 112)
PLAN = [('ナノガラス', 500329/7, 50000, '通年。季節要因なし。+55%増額して売上−19%'),
        ('害虫ブロッカー', 504023/7, 50000, '広告費4.31倍にして売上+5.3%。増分MER 0.14'),
        ('4WAY',        558298/7, 60000, '+85%増額して売上−12%')]
print(f"{'商品':16}{'現在/日':>10}{'提案/日':>10}{'削減/日':>10}{'削減率':>8}  理由")
dsum=0
for k,cur,new,why in PLAN:
    d=new-cur; dsum+=d
    print(f'{k:16}{cur:10,.0f}{new:10,}{d:+10,.0f}{d/cur*100:+7.1f}%  {why}')
print('-'*112)
print(f'{"合計":16}{sum(p[1] for p in PLAN):10,.0f}{sum(p[2] for p in PLAN):10,}{dsum:+10,.0f}')
print()
print(f'全店日予算 534,000 → {534000+dsum:,.0f}円/日（{dsum/534000*100:+.1f}%）')
w=-dsum*7
print(f'週あたり {w:,.0f}円の広告費が浮く。')
print(f'判定（7日後 8/12）: 全店の週次売上の減少が {w*be:,.0f}円 未満なら成功。')
print(f'  ＝ 直近7日 9,031,100円 に対して {9031100-w*be:,.0f}円 を上回っていればよい（{-w*be/9031100*100:.1f}%の減少まで許容）')
