def adopt(n, br, tgt):
    ia = INCA.get(n,{})
    pair = [ia[k] for k in ('曜日','全店') if k in ia]
    if len(pair) < 2 or br=='' or tgt=='': return None, ia
    def zone(v): return 0 if v < br else (1 if v < tgt else 2)
    if zone(pair[0]) != zone(pair[1]): return None, ia
    return round(sum(pair)/2, 2), ia

