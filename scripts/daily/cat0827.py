PRICEBYDATE, MIXEDDAY, price_on, mixed_qty = w['PRICEBYDATE'], w['MIXEDDAY'], w['price_on'], w['mixed_qty']
def daycost(d):
    t = 0
    for nm in S:
        if not nm or d not in S[nm] or not S[nm][d][0]: continue
        gd = S[nm][d][0]
        if nm in VARC:
            for grp, gg in VG[nm].get(d, {}).items():
                t += round(gg/3980)*(VARC[nm][0] if grp == '白緑' else VARC[nm][1])
        elif nm in PRICEBYDATE:
            q = mixed_qty(gd, *MIXEDDAY[nm][d]) if (nm in MIXEDDAY and d in MIXEDDAY[nm]) else round(gd/price_on(nm, d))
            t += q*COST[nm]
        else:
            t += round(gd/PRICE[nm])*COST[nm]
    return t
