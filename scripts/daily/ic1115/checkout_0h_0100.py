"""今日（11/15）0時台の 決済画面→払い終えた を、過去21日の0時台と並べる（2026-11-15 00:5x ユーザー「今時点の購入率は？決済に入った後の」）
入力: Shopify FROM sessions SHOW sessions, sessions_with_cart_additions, sessions_that_reached_checkout, sessions_that_completed_checkout TIMESERIES hour SINCE 2026-10-25 UNTIL 2026-11-15（00:5x 取得。UTC 15時台＝JST 0時台）
今日の0時台は途中（00:5x まで）。日中の数字なので判定・予算には使わない"""
import math
# JST の日付: (来訪, カート, 決済画面, 払い終えた) ＝ 前日 UTC 15:00 の行
P = {'10-25': (105, 5, 4, 1), '10-26': (91, 7, 7, 5), '10-27': (67, 3, 2, 1), '10-28': (82, 6, 6, 1), '10-29': (80, 1, 1, 1), '10-30': (72, 2, 2, 2), '10-31': (45, 1, 1, 1),
     '11-01': (65, 3, 4, 3), '11-02': (53, 4, 4, 3), '11-03': (94, 4, 2, 2), '11-04': (91, 6, 6, 3), '11-05': (104, 5, 4, 2), '11-06': (75, 5, 4, 3), '11-07': (68, 5, 5, 1),
     '11-08': (59, 3, 3, 0), '11-09': (70, 4, 3, 2), '11-10': (57, 3, 3, 1), '11-11': (43, 3, 3, 3), '11-12': (68, 4, 4, 3), '11-13': (54, 2, 2, 1), '11-14': (65, 5, 6, 3)}
T = (57, 2, 3, 1)
ck = sum(v[2] for v in P.values()); cp = sum(v[3] for v in P.values()); p = cp / ck
r = {d: v[3] / v[2] for d, v in P.items() if v[2]}
low = sum(1 for x in r.values() if x < T[3] / T[2])
pr = sum(math.comb(T[2], j) * p ** j * (1 - p) ** (T[2] - j) for j in range(T[3] + 1))
print(f'今日 0時台（00:5x まで）: 来訪 {T[0]}・カート {T[1]}・決済画面 {T[2]}・払い終えた {T[3]}（{T[3]/T[2]*100:.0f}%）')
print(f'過去21日の0時台: 決済画面 {ck}・払い終えた {cp}（{p*100:.0f}%）・日ごとの最小 {min(r.values())*100:.0f}%〜最大 {max(r.values())*100:.0f}%・今日より低い日 {low}/21')
print(f'ふだんの {p*100:.0f}% なら、決済画面3人で払い終えるのが1人以下になる確率 {pr*100:.0f}%')
