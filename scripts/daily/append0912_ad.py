"""2026-09-12 の広告費をCSVへ追記。health_check(8/14-9/12実測) − CSV(8/14-9/11実測) の差。
   窓の検証: 3D足臭リセットブラシ HC 85,838 − CSV 85,838 = **0円ちょうど**（11日連続で成立）。
   窓開始を8/13と仮定すると4キャンペーンが負値になり不成立。8/14で確定。"""
import csv
D = '2026-09-12'
AD = [('ナノガラス脱毛パッド', 77681), ('W固定スマホ車載ホルダー', 30864), ('快適マジックインソール', 27815),
      ('伸縮ガラスクリーナー', 17093), ('ムダ毛シェーバー', 11188), ('カタログ全部（テスト）', 10859),
      ('バランスケアスリッパ', 10076), ('高見えレザーヘッドレストフック', 9375),
      ('ナノバブルシャワーヘッド', 9115), ('4-in-1マルチクリーナー', 8590), ('姿勢サポートチェア', 7026)]
TOT = sum(v for _, v in AD); assert TOT == 219682, TOT
p = 'data/daily/daily_ad.csv'
with open(p, encoding='utf-8') as f:
    assert not any(r and r[0] == D for r in csv.reader(f)), f'{D} が既にある'
with open(p, 'a', encoding='utf-8', newline='') as f:
    w = csv.writer(f)
    for c, v in AD: w.writerow([D, c, v])
print(f'{p} に {len(AD)}行 追記 ／ 9/12 広告費合計 {TOT:,}円')
