"""2026-08-31 朝: 8/30終日が確定したので、8/30夕方に出した「インソール不調」の結論を検算し直す。
   すべて Shopify 実測（ShopifyQL）。★日中の部分日と終日を必ず並べる。"""
import math

# インソール campaign 52554797283012（全流入）: (日, セッション, カート追加, 完了)
ALL = [('08/29 終日', 450, 27, 14), ('08/30 18:21時点', 266, 7, None), ('08/30 終日', 396, 19, 6)]
# 同 × referrer_name=instagram
IG  = [('08/29 終日', 314, 23), ('08/30 18:21時点', 166, 6), ('08/30 終日', 245, 16)]
# 全店（Shopify実測）
ST  = [('08/29 終日', 3537, 221), ('08/30 終日', 3310, 207)]
# 全店 instagram
STIG = [('08/29 終日', 2298, 153), ('08/30 終日', 2060, 136)]
# インソール campaign のカート追加率 日次（8/19-29 = 判定に使う基準窓）
BASE = [(161,11),(233,20),(199,22),(254,18),(270,22),(343,22),(357,17),(226,23),(380,29),(414,20),(450,27)]

print('■ ① 8/30夕方に見た数字と、終日確定の数字')
print(f'  {"":<18}{"セッション":>11}{"カート追加":>11}{"率":>9}')
for l, s, c, *_ in ALL: print(f'  インソール全体 {l:<12}{s:>11,}{c:>11}{c/s:>9.2%}')
for l, s, c in IG:      print(f'  └Instagram   {l:<12}{s:>11,}{c:>11}{c/s:>9.2%}')
print()
for l, s, c in ST:      print(f'  全店         {l:<12}{s:>11,}{c:>11}{c/s:>9.2%}')
for l, s, c in STIG:    print(f'  全店Instagram {l:<12}{s:>10,}{c:>11}{c/s:>9.2%}')

print('\n■ ② 夕方の結論がどれだけ動いたか')
print(f'  インソール全体 カート追加率: 18:21時点 2.63% → **終日 {19/396:.2%}**')
print(f'  └Instagram              : 18:21時点 3.61% → **終日 {16/245:.2%}**')
print(f'  8/29比: 全体 {(19/396)/(27/450)-1:+.1%} ／ Instagram {(16/245)/(23/314)-1:+.1%}')
print(f'  対照: 全店 {(207/3310)/(221/3537)-1:+.1%} ／ 全店Instagram {(136/2060)/(153/2298)-1:+.1%}')

print('\n■ ③ 珍しさの再計算（基準は8/19-29の11日）')
bs = sum(s for s, _ in BASE); bc = sum(c for _, c in BASE); p0 = bc/bs
chi = sum((c - s*p0)**2/(s*p0*(1-p0)) for s, c in BASE); phi = chi/(len(BASE)-1)
def norm_cdf(x): return 0.5*(1+math.erf(x/math.sqrt(2)))
print(f'  基準 {bc}/{bs:,} = {p0:.2%} ／ 過分散 φ = {phi:.2f}')
for lbl, s, c in (('18:21時点（夕方に見た値）', 266, 7), ('終日確定', 396, 19)):
    z = (c - s*p0)/math.sqrt(s*p0*(1-p0)); za = z/math.sqrt(phi)
    print(f'  {lbl:<24} {c}/{s} = {c/s:.2%} → z {z:+.2f} / 過分散補正後 z {za:+.2f} '
          f'（片側 p = {norm_cdf(za):.1%} ≒ {1/norm_cdf(za):.0f}日に1回）')

print('\n■ ④ 終日で見た「どこが落ちたか」')
s9, c9, k9 = 450, 27, 14
s0, c0, k0 = 396, 19, 6
print(f'  セッション        {s9} → {s0}（{s0/s9-1:+.1%}）※全店は{3310/3537-1:+.1%}')
print(f'  カート追加率      {c9/s9:.2%} → {c0/s0:.2%}（{(c0/s0)/(c9/s9)-1:+.1%}）')
print(f'  カート→購入完了   {k9/c9:.1%} → {k0/c0:.1%}（{(k0/c0)/(k9/c9)-1:+.1%}）')
se = math.sqrt((k9/c9)*(1-k9/c9)/c9 + (k0/c0)*(1-k0/c0)/c0)
print(f'  └ カート→購入の差の z = {((k0/c0)-(k9/c9))/se:+.2f}（n=19と27。有意ではない）')
print(f'  実売(Shopify): 8/29 87,560円/22点 → 8/30 27,860円/7点（−68.2%）')
print('  → 落ち込みは「カート追加 −20%」×「カート→購入 −39%」の掛け算。ただし後者は n=19 で有意差なし')
