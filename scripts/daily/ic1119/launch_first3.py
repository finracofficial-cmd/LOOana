"""11/19 「360°も出したときは在庫表記だけどめっちゃ売れたよな？」: 10/20 以降に出した・出し直した商品の 最初の3日（11/18 までにある日だけ）を並べる。
表記は Shopify の今の商品名（11/18 の売上の取得・o1118/sales_1118_raw.json 等の元の商品名）による。入力は data/daily（w1118.py の積み直し）"""
import io, contextlib
g = {}
with contextlib.redirect_stdout(io.StringIO()): exec(open('scripts/daily/w1118.py').read(), g)
WIN, agg, A, ALLD = g['WIN'], g['agg'], g['A'], g['ALLD']
L = [('コードレスダブルミスト加湿器', '2026-10-20', '本日終了'), ('マグネットドアクッション', '2026-10-31', '本日終了'), ('ワイド水切りワイパー', '2026-11-04', '本日終了'),
     ('クリアビューレインガードフィルム', '2026-11-05', '本日終了'), ('シリコンホールド膝サポーター', '2026-11-08', '本日終了'), ('すき間収納シートポケット', '2026-11-11', '在庫セール'),
     ('防風あったか裏起毛パンツ', '2026-11-11', '本日終了'), ('3WAY着る電気ブランケット', '2026-11-13', '本日終了'), ('スマートノーズEMS美顔器', '2026-11-14', '本日終了'),
     ('携帯電動シェーバー', '2026-11-14', '本日終了'), ('快適マジックインソール', '2026-11-16', '本日終了'), ('360°マルチクリップ車載スマホホルダー', '2026-11-16', '在庫セール'),
     ('裏起毛タッチ防寒グローブ', '2026-11-17', '在庫セール'), ('高見えレザーヘッドレストフック', '2026-11-18', '在庫セール'), ('ポータブルヒートシーラー', '2026-11-18', '在庫セール')]
print('商品（表記）: 最初の3日の 個数/日・倍率・利益 ｜ 日ごとの 個数（倍率）')
for n, st, lab in L:
    ds = [d for d in ALLD if d >= st][:3]
    key = 'f' + n + st; WIN[key] = ds; N, DC, Q, K = agg(ds, key); a = A(ds, n); s = N.get(n, 0); k = K.get(n, 0)
    day = []
    for d in ds:
        kk = 'g' + n + d; WIN[kk] = [d]; N1, _, Q1, K1 = agg([d], kk); a1 = A([d], n)
        day.append(f"{d[5:]} {Q1.get(n,0)}個（{(N1.get(n,0)-K1.get(n,0))/a1:.2f}）" if a1 else f"{d[5:]} {Q1.get(n,0)}個（広告0）")
    print(f"  {n[:14]}（{lab}・{st[5:]}〜{len(ds)}日）: {Q.get(n,0)/len(ds):.1f}個/日・{(s-k)/a if a else 0:.2f}・{s-k-a:+,.0f} ｜ " + '・'.join(day))
