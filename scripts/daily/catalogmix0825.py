print('■ カタログ広告の消化先 — 季節物（7日 8/18-24・Meta product_id別実測）')
print(f'  {"商品":<24}{"消化":>9}{"インプ":>8}{"クリック":>8}{"CPM":>8}{"CTR":>8}{"CPC":>8}')
sc = si = sk = 0
for n, rows in sorted(SEASON.items(), key=lambda x: -sum(r[0] for r in x[1])):
    c = sum(r[0] for r in rows); i = sum(r[1] for r in rows); k = sum(r[2] for r in rows)
    sc += c; si += i; sk += k
    print(f'  {n:<24}{c:>9,}{i:>8,}{k:>8,}{c/i*1000:>8,.0f}{k/i:>8.2%}{(c/k if k else 0):>8,.0f}')
print(f'  {"── 季節物 計":<24}{sc:>9,}{si:>8,}{sk:>8,}{sc/si*1000:>8,.0f}{sk/si:>8.2%}{sc/sk:>8,.0f}')
oc, oi, ok = TOT_COST - sc, TOT_IMP - si, TOT_CLK - sk
print(f'  {"── 通年+新商品 計":<24}{oc:>9,}{oi:>8,}{ok:>8,}{oc/oi*1000:>8,.0f}{ok/oi:>8.2%}{oc/ok:>8,.0f}')
print(f'  {"── カタログ全体":<24}{TOT_COST:>9,}{TOT_IMP:>8,}{TOT_CLK:>8,}'
      f'{TOT_COST/TOT_IMP*1000:>8,.0f}{TOT_CLK/TOT_IMP:>8.2%}{TOT_COST/TOT_CLK:>8,.0f}')

