print(f'  季節物の CTR {sk/si:.2%} vs 通年+新商品 {ok/oi:.2%} → 季節物は {(sk/si)/(ok/oi)-1:+.0%}')
print(f'  季節物の CPM {sc/si*1000:,.0f}円 vs 通年+新商品 {oc/oi*1000:,.0f}円')

# 除外した場合の試算（クリック単価が通年+新商品の水準になると仮定）
print('\n■ 季節物を商品セットから外したときの試算')
print('  前提: 浮いた消化が「通年+新商品」と同じ CPC で回る（Metaが同じ面に出し続けるという仮定）')
new_clicks = TOT_COST / (oc / ok)
print(f'  同じ141,166円で取れるクリック: {TOT_CLK:,} → {new_clicks:,.0f}件（{new_clicks/TOT_CLK-1:+.0%}）')
CVR_ALL = 37 / TOT_CLK                    # カタログ全体のMeta基準CVR（実測）
print(f'  カタログ全体のCVR（Meta基準・実測）{CVR_ALL:.2%} が維持されるなら 購入 37 → {new_clicks*CVR_ALL:.0f}件')
print(f'  CPA {TOT_COST/37:,.0f}円 → {TOT_COST/(new_clicks*CVR_ALL):,.0f}円（分岐CPA 3,721円）')
print(f'  → 倍率 {3721/(TOT_COST/37):.2f} → {3721/(TOT_COST/(new_clicks*CVR_ALL)):.2f}')
print('  ⚠️ これは「CPCが改善する」ぶんだけの試算。CVRの改善は織り込んでいない（読めないため）')
