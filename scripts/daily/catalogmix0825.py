"""カタログ広告の消化が「どの商品」に流れているかを集計する。
Meta product_id別実測（7日 8/18-24・カタログキャンペーンのみ）。
季節物のバリアント行だけ転記し、通年/新商品はキャンペーン合計からの差で出す（転記量を減らして誤りを防ぐ）。"""
