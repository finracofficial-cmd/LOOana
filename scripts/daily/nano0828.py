"""2026-08-28 ナノガラス脱毛パッドの効率悪化の分解。
   注文UTM（utm_term=広告セットID）で帰属し、広告セット単位で採算を出す。
   ★数値はすべて実測。Shopify=注文行を1件ずつ数えた点数 / Meta=消化・クリック・頻度・リーチ。
   同一窓（JST 0:00-17:26）で8/27と並べる。"""

GP = 3980 - 757   # ナノガラス1点あたり粗利（売価−原価・白緑）
A2, A3 = 'adset2（ナノガラス2・広告A）', 'adset3（BC検証用・広告B/C）'

# Shopify 注文UTM帰属の点数（同一窓 JST 0:00-17:26）
ITEMS = {'8/27': {A2: 17, A3: 9, '広告外': 2},
         '8/28': {A2: 7,  A3: 5, '広告外': 2}}
# Meta 実測（8/28は17:26時点、8/27は終日）
SPEND28 = {A2: (39930, 528), A3: (12724, 164)}
SPEND27_DAY = {A2: (71871, 733), A3: (18174+3221, 184+23)}
FREQ = {'8/26 adset2': (1.0437, 20985), '8/27 adset2': (1.0149, 27783), '8/28 adset2': (1.0443, 17046),
        '8/26 adset3': (1.0599, 5964),  '8/27 adset3': (1.0791, 7410),  '8/28 adset3': (1.0581, 5477)}

print('■ ① 広告セット別の点数（同一窓 JST 0:00-17:26）')
print(f'{"帰属先":<30}{"8/27":>7}{"8/28":>7}{"差":>8}')
for k in (A2, A3, '広告外'):
    a, b = ITEMS['8/27'][k], ITEMS['8/28'][k]
    d = f'{b/a-1:+.0%}' if a else '—'
    print(f'  {k:<28}{a:>7}{b:>7}{b-a:>+5}({d})')
print(f'  {"合計":<28}{sum(ITEMS["8/27"].values()):>7}{sum(ITEMS["8/28"].values()):>7}')

print('\n■ ② 今日の広告セット別採算（分岐CPA = 1点あたり粗利 3,223円）')
print(f'{"広告セット":<30}{"消化":>9}{"クリック":>8}{"点数":>6}{"CPC":>7}{"クリック→購入":>12}{"CPA/点":>9}{"倍率":>7}')
tc = tk = ti = 0
for k, (c, kl) in SPEND28.items():
    i = ITEMS['8/28'][k]; tc += c; tk += kl; ti += i
    print(f'  {k:<28}{c:>9,}{kl:>8}{i:>6}{c/kl:>7,.0f}{i/kl:>12.2%}{c/i:>9,.0f}'
          f'{GP/(c/i):>7.2f}' + ('  🚨赤字' if GP/(c/i) < 1 else '  ✅黒字'))
print(f'  {"合計（広告帰属のみ）":<28}{tc:>9,}{tk:>8}{ti:>6}{tc/tk:>7,.0f}{ti/tk:>12.2%}'
      f'{tc/ti:>9,.0f}{GP/(tc/ti):>7.2f}')

print('\n■ ③ 配信配分は動いていない（＝Metaが偏らせたわけではない）')
s28 = SPEND28[A2][0]/(SPEND28[A2][0]+SPEND28[A3][0])
s27 = SPEND27_DAY[A2][0]/(SPEND27_DAY[A2][0]+SPEND27_DAY[A3][0])
print(f'  adset2の消化シェア  8/27終日 {s27:.1%} → 8/28 {s28:.1%}（ほぼ不変）')
print(f'  adset2の点数シェア  8/27同窓 {17/26:.0%} → 8/28 {7/12:.0%}')

print('\n■ ④ 素材疲れではない（頻度・リーチ）')
for k, (f, r) in FREQ.items():
    print(f'  {k}  頻度 {f:.3f} / リーチ {r:>7,}')
print('  → 頻度1.02〜1.08。疲弊の閾値2.5に遠い。リーチも毎日1.7〜2.8万人と伸びている')

print('\n■ ⑤ 今日ここまでの損益（広告帰属分のみ）')
for k, (c, _) in SPEND28.items():
    i = ITEMS['8/28'][k]
    print(f'  {k:<28} 粗利 {i*GP:>7,} − 広告 {c:>7,} = {i*GP-c:>+8,}円')
print(f'  {"合計":<28} 粗利 {ti*GP:>7,} − 広告 {tc:>7,} = {ti*GP-tc:>+8,}円')

print('\n■ ⑥ 原因の切り分け')
print('  ・LP/価格/在庫/決済 → 除外。同じLPで走るadset3は3.05%出ている')
print('  ・配信面/年齢性別 → 除外（別途測定・ミックス不変）')
print('  ・素材疲れ → 除外（頻度1.04）')
print('  ・配信配分の偏り → 除外（消化シェア不変）')
print('  ・CPC → 除外（両セット76〜78円で同水準・むしろ平常より安い）')
print('  → 残るのは「adset2が今日拾った人の質」。'
      'Advantage+の自動拡張で毎日新しい層を掘っており、今日は薄い層に当たった形')
