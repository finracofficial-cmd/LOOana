FALLBACK=[]

def sold(period_gross, period_net, key):
    """販売数 = gross_sales ÷ 売価。gross は返品を引かないので『売れた数』が出る（net_items_sold は返品を引いた数）"""
    out={}
    for n,g in period_gross.items():
        p=PRICE_ALL.get(n)
        if p is None: out[n]=period_net[n]; FALLBACK.append((key,n,'売価未登録')); continue
        q=g/p
        if abs(q-round(q))>1e-6:
            out[n]=period_net[n]; FALLBACK.append((key,n,'窓内で売価が混在')); continue
        out[n]=round(q)
    return out
