# ⑤ 「たまたまか」を数字で詰める（過分散を入れる）
#    ★2026-08-28の反省: 二項分布のまま z を読むと珍しさを過大評価する。
#      日ごとに真の率が動く（過分散）ので、Pearson χ² から φ を出して z を割り戻す。
# ============================================================
print('\n■ ⑤ 「たまたま」かを数字で詰める')
