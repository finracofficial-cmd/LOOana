"""2026-09-08 バランスケアスリッパ 増額判定（12,000 → 15,000）。CSV実測のみ（w0906.py 経由）。

宣言済み基準（9/5に設定）: 「1日あたり利益 ≥ 12,000時代(8/31-9/2)の +8,997円」

★窓の取り方について正直に書く: 12,000→15,000 への変更日は特定できていない。
  8/30b のスナップショットでは12,000、9/05朝のMeta直読で15,000だった。その間のどこかで上がっている。
  そこで **15,000 と実測確認できている 9/05-9/06 を主窓**とし、変更が早かった場合に備えて
  9/03-9/06 の広い窓も併記する。**両方が同じ結論なら採用**（増分MERの①②2通り補正と同じ考え方）。
"""
import runpy
g = runpy.run_path('scripts/daily/w0906.py')
S, AD, STORE, MAP, COST, PRICE = g['S'], g['AD'], g['STORE'], g['MAP'], g['COST'], g['PRICE']
ALLD = sorted(STORE)
N = 'バランスケアスリッパ'

def blk(dd):
    s = sum(S[N][d][0]-S[N][d][1] for d in dd if d in S[N])
    a = sum(AD[MAP.get(N, N)].get(d, 0) for d in dd)
    q = sum(round(S[N][d][0]/PRICE[N]) for d in dd if d in S[N])
    c = q*COST[N]
    return s, q, a, c, s-c-a

P1 = ['2026-08-31', '2026-09-01', '2026-09-02']
BASE = blk(P1)[4]/len(P1)
print(f'■ 基準（宣言済み・12,000時代 8/31-9/2）')
s, q, a, c, p = blk(P1)
print(f'  実売{s:>8,} {q:>3}点 広告{a:>8,.0f} 原価{c:>7,} → 利益{p:>+9,.0f} ／ **1日あたり {BASE:>+8,.0f}円**')

print(f'\n■ 判定（15,000時代）')
ok = []
for lbl, dd in [('主窓 9/05-9/06（Meta直読で15,000を確認済み）', ['2026-09-05', '2026-09-06']),
                ('広窓 9/03-9/06（変更が早かった場合）', ['2026-09-03', '2026-09-04', '2026-09-05', '2026-09-06'])]:
    s, q, a, c, p = blk(dd); d = p/len(dd)
    j = d >= BASE; ok.append(j)
    print(f'  {lbl}')
    print(f'    実売{s:>8,} {q:>3}点 広告{a:>8,.0f} 原価{c:>7,} → 利益{p:>+9,.0f} ／ 1日あたり **{d:>+8,.0f}円** '
          f'→ {"✅合格" if j else "❌不合格"}（基準{BASE:,.0f}の{d/BASE:.0%}）')

print(f'\n  → {"✅ 両窓とも合格 → 15,000で据え置き" if all(ok) else ("❌ 両窓とも不合格 → 12,000へ戻す" if not any(ok) else "⚠️ 窓で結論が割れた → 判定保留・明日再判定")}')

print('\n■ 日別（参考）')
for d in ['2026-08-31', '2026-09-01', '2026-09-02', '2026-09-03', '2026-09-04', '2026-09-05', '2026-09-06']:
    s, q, a, c, p = blk([d])
    print(f'  {d[5:]}({g["wd"](d)}) 実売{s:>7,} {q:>2}点 広告{a:>7,.0f} → 利益{p:>+8,.0f}')

print('\n■ 3窓判定（参考）')
for k in (3, 5, 7):
    i = ALLD.index('2026-09-06'); dd = ALLD[i-k+1:i+1]
    s, q, a, c, p = blk(dd)
    print(f'  {k}日 {dd[0][5:]}-{dd[-1][5:]}: MER{s/a:5.2f} 分岐{1/(1-c/s):4.2f} 余裕{s/a-1/(1-c/s):+5.2f} 利益{p:>+9,.0f}')
