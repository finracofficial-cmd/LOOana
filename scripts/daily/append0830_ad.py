"""2026-08-30 の広告費をCSVへ追記。
   health_check(8/01-8/30 実測) − CSV(8/01-8/29 実測) の差。推計ではない。
   窓の検証: ビジュアル耳かき（8/28開始）は CSV 10,675 / HC 20,554 → 8/30 = 9,879円。
   3D足臭は 8/29に停止済みで HC=CSV=85,838 → 8/30 = 0円（停止と整合）。"""
import csv
D = '2026-08-30'
AD = [('ナノガラス脱毛パッド', 87300), ('W固定スマホ車載ホルダー', 32088), ('快適マジックインソール', 28842),
      ('カタログ全部（テスト）', 17731), ('ムダ毛シェーバー', 17094), ('むくみ取りかっさ', 13440),
      ('姿勢サポートチェア', 13229), ('バランスケアスリッパ', 12966), ('2WAYシートボックス', 12719),
      ('ビジュアル耳かき', 9879), ('ナノバブルシャワーヘッド', 8340),
      ('完全遮光・接触冷感UVハット', 7898), ('偏光・調光サングラス', 2816)]
TOT = sum(v for _, v in AD)
assert TOT == 264342, TOT
p = 'data/daily/daily_ad.csv'
with open(p, encoding='utf-8') as f:
    assert not any(r and r[0] == D for r in csv.reader(f)), f'{D} が既にある'
with open(p, 'a', encoding='utf-8', newline='') as f:
    w = csv.writer(f)
    for c, v in AD: w.writerow([D, c, v])
print(f'{p} に {len(AD)}行 追記 ／ 8/30 広告費合計 {TOT:,}円（日予算255,000の {TOT/255000:.1%}）')
