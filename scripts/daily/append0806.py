def rewrite(path, hdr, rows):
    old=[r for r in csv.reader(open(path))][1:]
    old=[r for r in old if r and r[0]!=D]
    with open(path,'w',newline='') as f:
        w=csv.writer(f); w.writerow(hdr); w.writerows(old)
        for r in rows: w.writerow([D]+list(r))
