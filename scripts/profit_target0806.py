# -*- coding: utf-8 -*-
"""2026-08-06 「1日利益10万円（最低）／18万円（目標）」から逆算する
日次利益 = Σ 広告費_i × (MER_i × 粗利率_i − 1)
→ 「広告費1円あたり利益」= MER×粗利率−1 が正のものに金を置く。負のものだけ削る。
売上/個数/注文=Shopify実測、広告費=Meta実測。"""
import json, collections
SC='/tmp/claude-0/-home-user-LOOana/42be2ed9-9967-56df-ab9c-75166f45bbc9/scratchpad/'
rows=json.load(open(SC+'act0806.json',encoding='utf-8'))
# 本日ユーザー実施後の日予算
BUD={'4WAY':50000,'5WAY腰掛けファン':16250,'卓上冷感クーラー':10000,'3WAYサーキュレーター':0,
'形状記憶日傘':35000,'完全遮光・形状記憶':28000,'偏光・調光サングラス':22000,'完全遮光・接触冷感UVハット':8000,
'接触冷感UVパーカー':30000,'接触冷感UVアームカバー':17000,'瞬間冷感ポンチョ':9000,'害虫ブロッカー':45000,
'ナノガラス脱毛パッド':80000,'ムダ毛シェーバー':20000,'携帯電動シェーバー':11000,
'健康サンダル':13000,'バランスケアスリッパ':5000,'W固定スマホ車載ホルダー':15000,'姿勢サポートチェア':10000}
CATALOG=23000
R={r['n']:r for r in rows}
print('='*116)
print('① 広告費1円あたり利益 = MER × 粗利率 − 1　… ここが正なら「出すほど利益額が増える」')
print('='*116)
print(f"{'商品':<22}{'日予算':>8}{'MER':>6}{'粗利率':>7}{'1円あたり利益':>13}{'日予算での利益/日':>17}{'判定':>16}")
tot_b=0; tot_p=0; L=[]
for n,b in sorted(BUD.items(),key=lambda x:-x[1]):
    r=R[n]; 
    if not r['mer'] or b==0: continue
    gm=1-r['k']/r['s']; per=r['mer']*gm-1; L.append((n,b,r['mer'],gm,per))
    j='🚀出すほど増える' if per>0.5 else ('✅正だが薄い' if per>0 else '🚨出すほど減る')
    print(f'{n:<22}{b:>8,}{r["mer"]:>6.2f}{gm*100:6.1f}%{per:>+13.3f}{b*per:>+17,.0f}  {j}')
    tot_b+=b; tot_p+=b*per
print('-'*116)
print(f'{"広告あり計":<22}{tot_b:>8,}{"":>6}{"":>7}{"":>13}{tot_p:>+17,.0f}')
print(f'{"カタログ（Meta計上）":<22}{CATALOG:>8,}{"":>6}{"":>7}{"":>13}{7127:>+17,.0f}')
NONAD=(17369+8013+7442+3527+40200+4520-22202)/7   # 広告なし商品の7日利益/日
print(f'{"広告なし商品（自然流入）":<22}{0:>8,}{"":>6}{"":>7}{"":>13}{NONAD:>+17,.0f}')
DAILY=tot_p+7127+NONAD
print(f'{"→ 現在の日予算での 1日利益":<22}{tot_b+CATALOG:>8,}{"":>6}{"":>7}{"":>13}{DAILY:>+17,.0f}')
print()
print(f'  最低ライン 100,000円 に対して {DAILY-100000:+,.0f}円  ／ 目標 180,000円 に対して {DAILY-180000:+,.0f}円')
print()
print('='*116)
print('② 「削ると利益額はいくら減るか」— 今日の2件で実測')
print('='*116)
for n,cut,mm in [('3WAYサーキュレーター',16000,None),('卓上冷感クーラー',7000,1.75)]:
    r=R[n]; gm=1-r['k']/r['s']
    if mm is None:   # 全停止＝その商品の利益がまるごと消える
        dp=-r['p']/7
        print(f'  {n}: 停止 → 7日利益 {r["p"]:+,.0f}円 が消える = {dp:+,.0f}円/日（広告費は{r["a"]/7:,.0f}円/日 浮く）')
    else:
        ds=cut*mm; dp=cut-ds*gm
        print(f'  {n}: −{cut:,}円/日（限界MER {mm}）→ 売上−{ds:,.0f} 粗利−{ds*gm:,.0f} 対 広告費−{cut:,} = 利益 {dp:+,.0f}円/日')
print()
print('  ★ 一般式: 削減1円あたりの利益変化 = 1 − 限界MER × 粗利率')
print('     限界MER が 分岐MER（=1/粗利率）を上回っている限り、削れば削るほど利益額は必ず減る。')
print('     実測の限界MER: 4WAY 1.71-2.06 / 害虫 1.90-2.04 / 卓上 1.50-2.05 → 全部 分岐(1.4-1.7)超え')
print()
print('='*116)
print('③ 18万円/日 を達成する道は「削る」ではなく「1円あたり利益が高いところに出す」')
print('='*116)
L.sort(key=lambda x:-x[4])
print('  出すべき順（1円あたり利益の高い順）')
for n,b,m,gm,per in L[:8]:
    r=R[n]; head='余裕大' if (r['mer']-r['br'])>1.0 else ''
    print(f'    {n:<22} 1円あたり {per:+.3f}円   現予算 {b:>7,}   MER {m:.2f} / 分岐 {r["br"]:.2f} {head}')
print()
print('  削るべき（1円あたりが負のものだけ）')
for n,b,m,gm,per in L:
    if per<0: print(f'    {n:<22} 1円あたり {per:+.3f}円   現予算 {b:>7,} → 停止で利益 {-b*per:+,.0f}円/日 改善')
