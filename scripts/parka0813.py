"""接触冷感UVパーカー 3,980→4,980円（2026-08-13 09:58 JST 実施）の判定設計。
   基準日 = 直近7日 8/06-12 の Shopify実測 × Meta実測広告費。"""
Q,O,REV,AD,CLK = 113, 99, 437800, 204475, 2209     # 販売数/注文/売上(gross-値引)/広告費/Metaクリック
COST, OLD = 1434, 3980
DR = 1 - REV/(Q*OLD)                                # 実測の値引率
print(f"■ 基準（7日 8/06-12・実測）販売{Q}個 注文{O} 売上{REV:,} 広告{AD:,} 利益{REV-Q*COST-AD:,} "
      f"({(REV-Q*COST-AD)/REV*100:.1f}%) MER {REV/AD:.2f} CVR {O/CLK*100:.2f}% 値引率{DR*100:.2f}%\n")
print(f"{'売価':>7}{'原価率':>8}{'粗利/個':>9}{'分岐MER':>9}{'目標MER':>9}{'改善ライン':>10}{'黒字化ライン':>11}{'必要販売数':>10}")
for p in (OLD, 4480, 4980):
    gp=p-COST
    y=1-(OLD-COST)/gp if p>OLD else 0.0
    z=1-AD/(Q*gp)
    print(f"{p:>7,}{COST/p*100:7.2f}%{gp:9,}{1/(1-COST/p):9.3f}{1/(1-COST/p-0.35):9.3f}"
          f"{y*100:9.1f}%{z*100:10.1f}%{Q*(1-y):10.1f}")
print("\n■ 4,980円での見通し（CVRは全店の価格帯実測 3,980円4.06%→4,980円3.81% を適用＝【推計】）")
gp=4980-COST
for lbl,ratio in [('価格帯実測どおり(−6.2%)',3.81/4.06),('横ばい(0%)',1.0),('改善ライン(−28.2%)',1-(1-(OLD-COST)/gp)),
                  ('−35%',0.65),('黒字化ライン(−49.0%)',AD/(Q*gp))]:
    q=Q*ratio; g=q*4980; rev=g*(1-DR); pr=rev-q*COST-AD
    print(f"  {lbl:22} 販売{q:6.1f}個 売上{rev:>9,.0f} 利益{pr:>9,.0f} ({pr/rev*100:5.1f}%) "
          f"MER {rev/AD:.2f}  差 {pr-(REV-Q*COST-AD):+,.0f}円/7日")
print("\n■ 判定 8/20（実施+7日）— 第1指標=販売数 / 第2指標=CVR（値上げは必ず両方で読む）")
print(f"  ✅ 合格      販売数 ≥ 81個 かつ CVR ≥ 3.22%  → 粗利総額が値上げ前を上回る。4,980で確定")
print(f"  🟡 引き分け  販売数 58〜80個                  → 黒字は維持だが粗利総額は減る。4,480へ一段下げて再測定")
print(f"  🚨 不合格    販売数 < 58個                    → 赤字。3,980円へ戻す")
print(f"  ※ 引き分けCVR = {O/CLK*100:.2f}% × (2,546 ÷ 3,546) = {O/CLK*(OLD-COST)/gp*100:.2f}%")
