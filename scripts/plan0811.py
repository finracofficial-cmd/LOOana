# -*- coding: utf-8 -*-
import pickle
R=pickle.load(open('/tmp/rep0811.pkl','rb'))
N7,K7,A7=R['N7'],R['K7'],R['A7']
S=sum(N7.values()); K=sum(K7.values()); A=R['ACCT7']
print(f"■ 現状（7日 8/04-10）実売 {S:,} / 原価 {K:,}({K/S*100:.1f}%) / 広告 {A:,.0f}({A/S*100:.1f}%) / 利益 {S-K-A:,.0f} / 利益率 {(S-K-A)/S*100:.2f}%")
print(f"  30日 利益率 {(sum(R['N30'].values())-sum(R['K30'].values())-R['ACCT30'])/sum(R['N30'].values())*100:.2f}%  7月 32.88%\n")
# 打ち手（日予算の変更・週=×7）
PLAN=[('4WAY',28000,21000,'実施済み'),('接触冷感UVパーカー',30000,13000,'今日'),('5WAY腰掛けファン',16250,6500,'今日'),
('携帯電動シェーバー',8250,6000,'今日'),('完全遮光・接触冷感UVハット',12000,15000,'今日'),
('W固定スマホ車載ホルダー',32500,40000,'今日'),('瞬間冷感ポンチョ',9000,0,'8/12'),
('形状記憶日傘',35000,19000,'8/13'),('偏光・調光サングラス',22000,9000,'8/13')]
ds=dk=da=0
print(f"{'商品':22}{'日予算':>16}{'Δ/日':>9}{'限界MER':>8}{'Δ売上/週':>11}{'Δ原価/週':>10}{'Δ広告/週':>10}{'Δ利益/週':>10}{'実行':>8}")
for n,b0,b1,when in PLAN:
    s,k,a=N7[n],K7[n],A7[n]; cr=k/s; mer=s/a; mm=mer*0.7
    d=(b1-b0)*7; Δs=mm*d; Δk=Δs*cr; Δp=Δs-Δk-d
    ds+=Δs; dk+=Δk; da+=d
    print(f"{n[:22]:22}{f'{b0:,}→{b1:,}':>16}{b1-b0:>9,}{mm:>8.2f}{Δs:>11,.0f}{Δk:>10,.0f}{d:>10,.0f}{Δp:>10,.0f}{when:>8}")
NS,NK,NA=S+ds,K+dk,A+da
print(f"\n{'合計':22}{'':>16}{sum(b1-b0 for _,b0,b1,_ in PLAN):>9,}{'':>8}{ds:>11,.0f}{dk:>10,.0f}{da:>10,.0f}{ds-dk-da:>10,.0f}")
print(f"\n■ 実行後（7日ベース）")
print(f"  実売 {NS:,.0f}（{ds:+,.0f}）/ 原価 {NK:,.0f}({NK/NS*100:.1f}%) / 広告 {NA:,.0f}({NA/NS*100:.1f}%)")
print(f"  利益 {NS-NK-NA:,.0f}（{(NS-NK-NA)-(S-K-A):+,.0f}）/ **利益率 {(NS-NK-NA)/NS*100:.2f}%**（{(NS-NK-NA)/NS*100-(S-K-A)/S*100:+.2f}pt）/ MER {NS/NA:.2f}")
print(f"  1日利益 {(S-K-A)/7:,.0f} → {(NS-NK-NA)/7:,.0f}円（最低ライン100,000円・目標180,000円）")
print(f"  全店日予算 427,500 → {427500+sum(b1-b0 for _,b0,b1,_ in PLAN):,}円")
print("\n■ 感度（限界MERを平均×0.6 / ×0.8 に振った場合の実行後利益率）")
for f in (0.6,0.8):
    ds2=dk2=0
    for n,b0,b1,_ in PLAN:
        s,k,a=N7[n],K7[n],A7[n]; cr=k/s; mm=(s/a)*f; d=(b1-b0)*7
        ds2+=mm*d; dk2+=mm*d*cr
    NS2,NK2,NA2=S+ds2,K+dk2,A+da
    print(f"  ×{f}: 利益率 {(NS2-NK2-NA2)/NS2*100:.2f}% / 週利益 {NS2-NK2-NA2:,.0f}円（{(NS2-NK2-NA2)-(S-K-A):+,.0f}）")
print("\n■ さらに原価交渉を足した場合（主力3品 ナノガラス749→650・4WAY1730→1550・害虫867→780）")
CUT={'ナノガラス脱毛パッド':(752,650),'4WAY':(1730,1550),'害虫ブロッカー':(867,780)}
g=0
for n,(o,nw) in CUT.items():
    q=R['Q7'][n]; g+=q*(o-nw)
    print(f"  {n[:20]:20} {q}個 × {o-nw}円 = 週+{q*(o-nw):,}円")
print(f"  合計 週+{g:,}円 → 実行後利益率 {(NS-NK-NA+g)/NS*100:.2f}%（さらに+{g/NS*100:.2f}pt）/ 週利益 {NS-NK-NA+g:,.0f}円")
