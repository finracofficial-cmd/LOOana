print()
print('=' * 100)
print('シフトシェア分解: 「購入効率（購入数÷広告費）」の悪化はどこから来たか')
print('=' * 100)
E0, E1 = Q0/C0, Q1/C1
print(f'購入効率 {E0*10000:.2f}件/万円 → {E1*10000:.2f}件/万円  ({(E1/E0-1)*100:+.1f}%)')

both = set(P0) & set(P1)
onlyP0 = set(P0) - set(P1)          # 撤退
onlyP1 = set(P1) - set(P0)          # 新規

within = mix = 0.0
det = []
for k in both:
    s0, s1 = P0[k][0]/C0, P1[k][0]/C1
    e0, e1 = P0[k][3]/P0[k][0], P1[k][3]/P1[k][0]
    w = s0*(e1-e0); m = (s1-s0)*e0; x = (s1-s0)*(e1-e0)
    within += w + x*0.5; mix += m + x*0.5      # 交互作用は折半
    det.append((k, s0, s1, e0, e1, (w+m+x)))

new_eff = sum(P1[k][0]/C1*(P1[k][3]/P1[k][0]) for k in onlyP1)
exit_eff = -sum(P0[k][0]/C0*(P0[k][3]/P0[k][0]) for k in onlyP0)
# 継続商品のシェア縮小分は mix に入っているので、新規/撤退は「その分の枠を誰が持ったか」を表す
