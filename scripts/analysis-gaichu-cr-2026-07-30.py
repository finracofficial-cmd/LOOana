def sel(days,adset=None,ad=None):
    rs=[r for r in R if r[0] in days and (adset is None or r[1]==adset) and (ad is None or r[2]==ad)]
    c=sum(r[3] for r in rs); i=sum(r[4] for r in rs); k=sum(r[5] for r in rs)
    p=sum(r[7] for r in rs); v=sum(r[8] for r in rs)
    return dict(cost=c,imp=i,clk=k,pur=p,val=v,ctr=k/i if i else 0,cvr=p/k if k else 0,
                cpa=c/p if p else 0,roas=v/c if c else 0)
def show(lbl,a,b):
    print(f'【{lbl}】')
    for nm,x in (('前',a),('後',b)):
        print(f'  {nm}: 消化{x["cost"]:,} クリック{x["clk"]:,} 購入{x["pur"]} CVR{x["cvr"]*100:.2f}% CPA{x["cpa"]:,.0f} ROAS{x["roas"]:.2f}')
    z=(b['pur']-b['clk']*a['cvr'])/math.sqrt(b['clk']*a['cvr']) if b['clk'] else 0
    print(f'  → CVR{(b["cvr"]/a["cvr"]-1)*100:+.1f}% / CPA{(b["cpa"]/a["cpa"]-1)*100:+.1f}% / '
          f'期待購入{b["clk"]*a["cvr"]:.1f}件 vs 実際{b["pur"]}件 = {z:+.2f}σ\n')

