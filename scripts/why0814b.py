# -*- coding: utf-8 -*-
"""売上減の要因を対数分解。売上 = 注文数 × 点数/注文 × 単価/点。すべてShopify実測。"""
import math
A=('7/09-15',1554,2057,9373608,2642454)   # 注文, 点数, gross, 原価
B=('8/07-13',1110,1345,5930880,1634312)
for l,o,i,g,c in (A,B):
    print(f"  {l:10} 注文{o:5,}  点数{i:5,}  売上{g:>10,}  粗利{g-c:>10,}  "
          f"点数/注文 {i/o:.3f}  単価/点 {g/i:,.0f}円  AOV {g/o:,.0f}円  粗利率 {(g-c)/g*100:.1f}%")
lo,li,lg,lc=A[1],A[2],A[3],A[4]; ro,ri,rg,rc=B[1],B[2],B[3],B[4]
tot=math.log(rg/lg)
f1=math.log(ro/lo); f2=math.log((ri/ro)/(li/lo)); f3=math.log((rg/ri)/(lg/li))
print(f"\n■ 売上 {lg:,} → {rg:,}（{rg/lg*100-100:+.1f}%）の要因分解")
for n,v in [('① 注文数',f1),('② 点数/注文（セット買い）',f2),('③ 単価/点（商品構成）',f3)]:
    print(f"  {n:26} {v/tot*100:5.1f}%   （{math.exp(v)*100-100:+.1f}%）")
print(f"  合計 {(f1+f2+f3)/tot*100:.1f}%")
print(f"\n  → セット買いの寄与は {f2/tot*100:.0f}%。{f1/tot*100:.0f}%は注文数そのものが減ったこと")
print(f"\n■ 「見かけ上」ではない — 粗利も同じだけ減っている")
print(f"  粗利 {lg-lc:,} → {rg-rc:,}（{(rg-rc)/(lg-lc)*100-100:+.1f}%）  売上と同率")
print(f"  粗利率だけは {(lg-lc)/lg*100:.1f}% → {(rg-rc)/rg*100:.1f}% と改善（原価の安い商品に主力が移ったため）")
print(f"  → 「安く売るようになった」わけではないが、売上も粗利も実額で {rg/lg*100-100:.1f}% 減っている")
print(f"\n■ 本日 8/14（JST 0-8時・完了分のみ）")
print(f"  {'':16}{'売上':>10}{'注文':>7}{'AOV':>9}")
print(f"  {'8/14(金)':16}{129400:10,}{26:7}{129400/26:9,.0f}")
print(f"  {'8/13(木)':16}{163816:10,}{29:7}{163816/29:9,.0f}")
t=math.log(129400/163816); a=math.log(26/29); b=t-a
print(f"  分解: 注文数 {a/t*100:.0f}%（{math.exp(a)*100-100:+.1f}%） ／ 客単価 {b/t*100:.0f}%（{math.exp(b)*100-100:+.1f}%）")
print(f"  → 今日はほぼ半々。5週間のトレンド（注文7割）とは違う形")
