# -*- coding: utf-8 -*-
"""3窓判定に基づくプランと、昨日の『利益率30%狙い』プランの比較。"""
import pickle
R=pickle.load(open('/tmp/rep0811.pkl','rb'))
N7,K7,A7=R['N7'],R['K7'],R['A7']
S=sum(N7.values()); K=sum(K7.values()); A=R['ACCT7']
def run(plan,label):
    ds=dk=da=0; rows=[]
    for n,b0,b1 in plan:
        s,k,a=N7[n],K7[n],A7[n]; cr=k/s; mm=(s/a)*0.7; d=(b1-b0)*7
        Δs=mm*d; Δk=Δs*cr; ds+=Δs; dk+=Δk; da+=d
        rows.append((n,b0,b1,Δs-Δk-d))
    NS,NK,NA=S+ds,K+dk,A+da
    print(f"\n■ {label}")
    for n,b0,b1,p in sorted(rows,key=lambda x:-x[3]):
        print(f"   {n[:22]:22} {b0:>7,} → {b1:>7,}   週{p:>+9,.0f}円")
    print(f"   ---- 実売 {NS:,.0f} / 原価 {NK:,.0f} / 広告 {NA:,.0f}")
    print(f"   ---- 週利益 {NS-NK-NA:,.0f}（{(NS-NK-NA)-(S-K-A):+,.0f}）／利益率 {(NS-NK-NA)/NS*100:.2f}%（{(NS-NK-NA)/NS*100-(S-K-A)/S*100:+.2f}pt）")
    print(f"   ---- 1日利益 {(NS-NK-NA)/7:,.0f}円／日予算 427,500 → {427500+sum(b1-b0 for _,b0,b1 in plan):,}円")
    return NS-NK-NA,(NS-NK-NA)/NS
print(f"■ 現状（7日 8/04-10）週利益 {S-K-A:,.0f} / 利益率 {(S-K-A)/S*100:.2f}% / 1日利益 {(S-K-A)/7:,.0f}円 / 日予算 427,500")
A_=[('瞬間冷感ポンチョ',9000,0),('携帯電動シェーバー',8250,4000),('4WAY',28000,21000),
    ('完全遮光・形状記憶',21000,15750),('偏光・調光サングラス',22000,16500),
    ('W固定スマホ車載ホルダー',32500,40000),('ナノガラス脱毛パッド',80000,96000),
    ('完全遮光・接触冷感UVハット',12000,15000)]
B_=[('瞬間冷感ポンチョ',9000,0),('携帯電動シェーバー',8250,6000),('4WAY',28000,21000),
    ('完全遮光・形状記憶',21000,15750),('偏光・調光サングラス',22000,9000),
    ('W固定スマホ車載ホルダー',32500,40000),('完全遮光・接触冷感UVハット',12000,15000),
    ('接触冷感UVパーカー',30000,13000),('5WAY腰掛けファン',16250,6500),('形状記憶日傘',35000,19000)]
pa,ra=run(A_,'案A：3窓判定に素直に従う（ナノガラス増額あり）')
pb,rb=run([x for x in A_ if x[0]!='ナノガラス脱毛パッド'],'案A′：ナノガラスだけ据え置き（ユーザー判断を尊重）')
pc,rc=run(B_,'案B：昨日の「利益率30%狙い」プラン（参考・パーカーと5WAYも削る）')
print(f"\n■ 比較")
print(f"  案A   週利益 {pa:>9,.0f}  利益率 {ra*100:.2f}%")
print(f"  案A′  週利益 {pb:>9,.0f}  利益率 {rb*100:.2f}%")
print(f"  案B   週利益 {pc:>9,.0f}  利益率 {rc*100:.2f}%")
print(f"\n  案B は案A′より 利益率 {(rc-rb)*100:+.2f}pt だが 週利益 {pc-pb:+,.0f}円")
print(f"  → パーカーと5WAYと日傘短を削ると、率は{(rc-rb)*100:+.2f}pt動くが額は{pc-pb:+,.0f}円")
