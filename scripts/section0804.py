"""2026-08-04 「おすすめ商品セクションを日曜に出してから悪化した」の検証
全データShopify実測（datarules.py の分担どおり。広告は使わない）。
前週(7/21-27) vs 後週(7/28-8/03) の同曜日7日ペアで、
①ファネル各段の段差 ②商品内の複数買い率 ③値引き率 を比較する。
"""
import math

# 日次ファネル（Shopify sessions実測）
F = {  # date: (sessions, cart, checkout, complete)
 '07-14':(6030,463,410,201),'07-15':(5717,463,411,213),'07-16':(6170,444,412,192),
 '07-17':(6050,441,397,208),'07-18':(7282,482,431,226),'07-19':(7229,466,413,216),
 '07-20':(7983,548,492,259),'07-21':(7718,497,447,231),'07-22':(8162,613,531,279),
 '07-23':(7528,531,466,241),'07-24':(7432,496,458,228),'07-25':(7422,506,465,234),
 '07-26':(8583,591,527,281),'07-27':(7030,432,377,199),'07-28':(7182,510,448,222),
 '07-29':(7479,509,432,221),'07-30':(7409,473,422,225),'07-31':(6127,393,358,182),
 '08-01':(7830,501,445,225),'08-02':(8042,570,505,263),'08-03':(6238,409,359,187),
 '08-04':(6639,419,356,181),
}
# 日次売上（Shopify実測 gross, disc, items, orders）
D = {
 '07-21':(1411244,57001,316,235),'07-22':(1778476,78169,380,286),'07-23':(1537436,63580,332,250),
 '07-24':(1376532,57140,307,233),'07-25':(1434076,54509,312,244),'07-26':(1693656,69195,371,288),
 '07-27':(1233380,56152,270,205),'07-28':(1339052,47883,290,228),'07-29':(1241268,41071,269,222),
 '07-30':(1326288,44555,296,234),'07-31':(1104724,39921,252,190),'08-01':(1339256,38980,291,232),
 '08-02':(1550660,58542,343,267),'08-03':(1045336,32301,238,187),
}
PRE  = ['07-21','07-22','07-23','07-24','07-25','07-26','07-27']
POST = ['07-28','07-29','07-30','07-31','08-01','08-02','08-03']

print('=' * 100)
print('① ファネル日次 — 展開日を境に段差があるか（Shopify実測）')
print('=' * 100)
print(f"{'日':8}{'セッション':>8}{'カート追加率':>10}{'カートCO':>8}{'CO完了':>8}{'CVR':>7}")
for d, (s, c, r, p) in F.items():
    mark = ' ←7/26(日)' if d == '07-26' else (' ←7/28 値引き段差' if d == '07-28' else '')
    print(f'{d:8}{s:8,}{c/s*100:9.2f}%{r/c*100:7.1f}%{p/r*100:7.1f}%{p/s*100:6.2f}%{mark}')

def fun(days):
    s = sum(F[d][0] for d in days); c = sum(F[d][1] for d in days)
    r = sum(F[d][2] for d in days); p = sum(F[d][3] for d in days)
    return s, c, r, p
s0, c0, r0, p0 = fun(PRE); s1, c1, r1, p1 = fun(POST)
print()
print(f'{"":18}{"前週7/21-27":>12}{"後週7/28-8/3":>13}{"変化":>9}')
for lab, a, b in [('セッション', s0, s1), ('カート追加率', c0/s0, c1/s1),
                  ('カート→CO', r0/c0, r1/c1), ('CO完了', p0/r0, p1/r1), ('CVR', p0/s0, p1/s1)]:
    if a > 1:
        print(f'{lab:18}{a:12,}{b:13,}{(b/a-1)*100:+8.1f}%')
    else:
        print(f'{lab:18}{a*100:11.2f}%{b*100:12.2f}%{(b/a-1)*100:+8.1f}%')

print()
print('=' * 100)
print('② 買い方の変化（同曜日7日ペア・Shopify実測）')
print('=' * 100)
def sales(days):
    g = sum(D[d][0] for d in days); x = sum(D[d][1] for d in days)
    i = sum(D[d][2] for d in days); o = sum(D[d][3] for d in days)
    return g, x, i, o
g0, x0, i0, o0 = sales(PRE); g1, x1, i1, o1 = sales(POST)
for lab, a, b in [('点数/注文', i0/o0, i1/o1), ('値引き率', x0/g0, x1/g1),
                  ('AOV(値引後)', (g0-x0)/o0, (g1-x1)/o1)]:
    f = '{:.3f}' if a < 10 else '{:,.0f}'
    if a < 1: f = '{:.2%}'
    print(f'{lab:14}{f.format(a):>10} → {f.format(b):>10}  ({(b/a-1)*100:+.1f}%)')

print()
print('③ 商品内の複数買い率（ミックス変化の影響を除去）— 点数/注文 前週→後週')
PR = {  # name: (pre_items, pre_orders, post_items, post_orders)
 '害虫ブロッカー':(357,203,263,157), '4WAY':(411,314,272,214), 'ナノガラス':(251,230,328,310),
 '形状記憶日傘':(291,247,206,176), 'ポンチョ':(62,41,57,38), '5WAY':(72,49,100,74),
 '卓上':(124,104,66,60), 'パーカー':(164,148,163,145), 'アームカバー':(58,49,55,50),
}
w = 0; tot = 0
for k, (a, b, c, dd) in PR.items():
    r0_ = a/b; r1_ = c/dd
    print(f'  {k:14}{r0_:6.3f} → {r1_:6.3f}  ({(r1_/r0_-1)*100:+.1f}%)')
    w += (r1_/r0_-1) * dd; tot += dd
print(f'  注文数加重平均の変化: {w/tot*100:+.1f}%')

print()
print('④ 害虫ブロッカーの値引き率（数量割引の代理指標。まとめ買いの値引きが最大の商品）')
print(f'  前週 {130743/1420860*100:.2f}% → 後週 {87759/1050720*100:.2f}%')
print(f'  点数/注文 {357/203:.3f} → {263/157:.3f} ({(263/157)/(357/203)*100-100:+.1f}%)')
